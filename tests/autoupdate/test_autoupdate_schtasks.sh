# ^ invariant cmd /V:ON (a machine or user setting) expands !x! inside a set line; the wrapper switches delayed expansion off, a ! in HOME arrives as typed
# ^ why the probe takes the wrapper's own setlocal and set lines, not a copy; only the real lines show what the task would do
test_a_bang_in_home_survives_cmd_with_delayed_expansion_on() {
    local probe="$SANDBOX/bang-probe.cmd" home="$SANDBOX/bang!x"
    au_begin || return 1
    mkdir -p -- "$home" || return 1
    set_env HOME="$home"
    gsg_from co install --auto-update
    assert_rc 0 "install --auto-update with a ! in HOME"
    assert_eq "$(sed -n 2p "$(sch_cmd)" | tr -d '\r')" "$SCH_MARKER" "line 2 stays the marker, so wrappers of earlier installs stay ours"
    assert_eq "$(sed -n 3p "$(sch_cmd)" | tr -d '\r')" "setlocal DisableDelayedExpansion" "line 3 switches delayed expansion off"
    { printf '@echo off\r\n'; grep -E '^(setlocal|set )' "$(sch_cmd)"; printf '"%s/bin/bash.exe" -c "echo $HOME"\r\n' "$(cygpath -m /)"; } >"$probe" || return 1
    run_cap env -i "${LC_ENV[@]}" "${EXTRA_ENV[@]}" cmd //V:ON //c "$(sch_win "$probe")" </dev/null
    assert_rc 0 "the probe ran under cmd /V:ON"
    assert_eq "$(tr -d '\r' <<<"$OUT")" "$home" "bash reads the exact path back, the ! is not eaten"
    rm -f -- "$probe"
}

# ^ invariant a wrapper without the marker is a doctor PROBLEM (exit 1) and status says the interval is unknown; neither runs schtasks
test_a_foreign_wrapper_is_a_doctor_problem_and_status_says_the_interval_is_unknown() {
    sch_install
    assert_rc 0 "install --auto-update"
    sed -i '2d' "$(sch_cmd)" || return 1
    assert_not_contains "$(<"$(sch_cmd)")" "$SCH_MARKER" "the wrapper has lost its marker"
    mkdir -p -- "$SANDBOX/roots"
    : >"$SANDBOX/schtasks.log"
    gsg_installed status
    assert_contains "$OUT" "interval unknown, $(sch_cmd) is missing or not ours" "status cannot read the interval of a wrapper that is not ours"
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_rc 1 "doctor with a foreign wrapper"
    assert_contains "$OUT" "auto-update: timer inactive: $(sch_cmd) was not written by git-secret-guard" "the PROBLEM names the file"
    assert_contains "$OUT" "move it away and run: $AU_CO/bin/git-secret-guard install --auto-update" "and the whole fix"
    assert_eq "$(sch_log)" "" "status and doctor never run schtasks"
}

# ^ invariant a wrapper of an earlier install (marker on line 2, no setlocal) is ours, and a plain install writes it again with the line
test_a_plain_install_rewrites_an_older_wrapper_that_lacks_the_setlocal_line() {
    sch_install
    assert_rc 0 "install --auto-update"
    sed -i '3d' "$(sch_cmd)" || return 1
    assert_not_contains "$(<"$(sch_cmd)")" "setlocal" "the wrapper is now the older shape"
    : >"$SANDBOX/schtasks.log"
    gsg_from co install
    assert_rc 0 "a plain install"
    assert_eq "$(sed -n 3p "$(sch_cmd)" | tr -d '\r')" "setlocal DisableDelayedExpansion" "the line is back"
    assert_eq "$(sed -n 2p "$(sch_cmd)" | tr -d '\r')" "$SCH_MARKER" "the marker is still line 2"
    assert_eq "$(sch_log)" "" "and schtasks was not called"
}

