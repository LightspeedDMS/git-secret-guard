# shellcheck shell=bash disable=SC2153,SC2034

GSG_SERVICE_UNIT=git-secret-guard-doctor.service
GSG_TIMER_UNIT=git-secret-guard-doctor.timer
GSG_TIMER_MARKER='# generated by git-secret-guard install --with-timer; uninstall removes this file'

# ^ why these four, not the whole environment; the user manager passes none on, a custom one at install time made the timer's doctor report not installed
# ^ invariant values set (non-empty) when install ran are written by timer_env_lines and checked by timer_check_target
GSG_TIMER_ENV_NAMES=(XDG_DATA_HOME XDG_STATE_HOME XDG_CONFIG_HOME GIT_CONFIG_GLOBAL)

timer_env_lines() {
    local n
    for n in "${GSG_TIMER_ENV_NAMES[@]}"; do
        if [ -n "${!n:-}" ]; then printf 'Environment="%s=%s"\n' "$n" "${!n}"; fi
    done
}

# ^ invariant true only for a regular file (never a link) whose first line is the marker => install and uninstall touch only units they wrote
timer_unit_is_ours() {
    local first=""
    if [ ! -f "$1" ] || [ -L "$1" ]; then return 1; fi
    IFS= read -r first <"$1" || true
    [ "$first" = "$GSG_TIMER_MARKER" ]
}

# ^ why only GIT_CONFIG_GLOBAL, not the XDG variables; paths_init already refuses a relative XDG_* before any command runs
# ^ invariant shared by the systemd units and the launchd plist; a relative value would point nowhere once the manager starts doctor elsewhere
timer_check_config_global() {
    local what
    if [ -n "${GIT_CONFIG_GLOBAL:-}" ] && [ "${GIT_CONFIG_GLOBAL#/}" = "$GIT_CONFIG_GLOBAL" ]; then
        what="${GIT_CONFIG_GLOBAL//[[:cntrl:]]/?}"
        trunc_text "$what" 120
        printf '%s: GIT_CONFIG_GLOBAL must be an absolute path to go into the timer unit (got [%s]); nothing was changed\n' "$GSG_NAME" "$REPLY" >&2
        return 1
    fi
}

# ^ why refuse these characters, not escape them; a quote, backslash, % or $ means something to systemd inside a path, and refusing is simpler to prove right
# ^ invariant $1 = the directory of the git install found first; every path written into a unit is checked, and a unit of ours is the only one replaced
timer_check_values() {
    local what n
    local -a values=("$GSG_SHARE" "$GSG_UNIT_DIR" "$1")
    timer_check_config_global || return 1
    for n in "${GSG_TIMER_ENV_NAMES[@]}"; do
        if [ -n "${!n:-}" ]; then values+=("${!n}"); fi
    done
    for what in "${values[@]}"; do
        case "$what" in
            *'"'* | *\\* | *'%'* | *'$'*) ;;
            *[[:cntrl:]]*) ;;
            *) continue ;;
        esac
        printf '%s: %s cannot be written into a systemd unit (it holds a quote, a backslash, %% or $, or a control character); nothing was changed\n' "$GSG_NAME" "${what//[[:cntrl:]]/?}" >&2
        return 1
    done
}

timer_check_target() {
    local unit path
    timer_check_values "$1" || return 1
    for unit in "$GSG_SERVICE_UNIT" "$GSG_TIMER_UNIT"; do
        path="$GSG_UNIT_DIR/$unit"
        if { [ -e "$path" ] || [ -L "$path" ]; } && ! timer_unit_is_ours "$path"; then
            printf '%s: %s exists and was not written by git-secret-guard; move it away and run install again; nothing was changed\n' "$GSG_NAME" "$path" >&2
            return 1
        fi
    done
}

# ^ invariant prints the git dir ($1) first, followed by /usr/local/bin:/usr/bin:/bin, each directory once, in order
timer_unit_path() {
    local d out=""
    for d in "$1" /usr/local/bin /usr/bin /bin; do
        case ":$out:" in
            *":$d:"*) ;;
            *) out+="${out:+:}$d" ;;
        esac
    done
    printf '%s' "$out"
}

# ^ external a quoted ExecStart path and Environment="NAME=value" are valid unit syntax; verified by systemd-analyze --user verify in tests/test_timer.sh
# ^ external the user manager has its own PATH; the unit carries the PATH of the git install found first, the same git doctor needs
timer_service_text() {
    printf '%s\n' "$GSG_TIMER_MARKER" '[Unit]' 'Description=git-secret-guard weekly coverage report (doctor)' '' '[Service]' 'Type=oneshot' 'TimeoutStartSec=1h' \
        "Environment=\"PATH=$(timer_unit_path "$1")\""
    timer_env_lines
    printf '%s\n' "ExecStart=\"$GSG_SHARE/bin/git-secret-guard\" doctor"
}

timer_timer_text() {
    printf '%s\n' "$GSG_TIMER_MARKER" '[Unit]' 'Description=git-secret-guard weekly coverage report (doctor)' '' '[Timer]' \
        'OnCalendar=weekly' 'Persistent=true' "Unit=$GSG_SERVICE_UNIT" '' '[Install]' 'WantedBy=timers.target'
}

# ^ invariant a unit appears complete or not at all => temp file beside it, rename after the write
timer_write_unit() {
    local path="$1" tmp
    tmp="$(mktemp "${path%/*}/.gsg-unit.XXXXXX")" || return 1
    if ! printf '%s\n' "$2" >"$tmp" || ! chmod 644 -- "$tmp" || ! mv -f -- "$tmp" "$path"; then
        rm -f -- "$tmp"
        return 1
    fi
}

timer_write_units() {
    mkdir -p -- "$GSG_UNIT_DIR" || return 1
    timer_write_unit "$GSG_UNIT_DIR/$GSG_SERVICE_UNIT" "$(timer_service_text "$1")" || return 1
    timer_write_unit "$GSG_UNIT_DIR/$GSG_TIMER_UNIT" "$(timer_timer_text)"
}
