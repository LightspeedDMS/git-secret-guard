test_a_plain_install_rewrites_a_changed_update_plist_without_launchctl() {
    lau_install --auto-update || return 1
    printf '<!-- edited by hand -->\n' >>"$(upd_plist)" || return 1
    lc_path_without launchctl || return 1
    : >"$SANDBOX/launchctl.log"
    gsg_from co install
    assert_rc 0 "plain install with no launchctl on PATH"
    assert_not_contains "$(<"$(upd_plist)")" "edited by hand" "the plist is ours and changed, so it is rewritten"
    assert_eq "$(sed -n "${UPD_MARKER_LINE}p" "$(upd_plist)")" "$UPD_PLIST_MARKER" "with its marker again"
    assert_eq "$(launchctl_log)" "" "launchctl was not called"
    assert_contains "$OUT" "updated the auto-update timer $(upd_plist)" "the output says so"
    assert_eq "$(state_value auto_update)" yes "auto-update stays recorded"
    printf 'not ours\n' >"$(upd_plist)" || return 1
    gsg_from co install
    assert_rc 0 "plain install over a foreign plist"
    assert_eq "$(<"$(upd_plist)")" "not ours" "the foreign plist is untouched"
}

test_the_update_plist_passes_plutil_lint_and_every_value_reads_back() {
    local key
    command -v plutil >/dev/null 2>&1 || skip_test "plutil is not available"
    lau_install --auto-update || return 1
    run_cap plutil -lint "$(upd_plist)"
    assert_rc 0 "plutil -lint"
    for key in "Label=$UPD_LABEL" "ProgramArguments.1=$LC_DATA/bin/git-secret-guard" "ProgramArguments.2=update" \
        "StartInterval=$UPD_INTERVAL_SECONDS" "StandardOutPath=$LC_STATE/update.log"; do
        run_cap plutil -extract "${key%%=*}" raw -o - "$(upd_plist)"
        assert_eq "$OUT" "${key#*=}" "plutil reads ${key%%=*} back"
    done
}

test_a_failing_bootstrap_of_the_update_agent_keeps_the_hook_and_a_rerun_loads_it() {
    lau_begin || return 1
    printf 'bootstrap' >"$SANDBOX/launchctl.fail" || return 1
    gsg_from co install --auto-update
    assert_rc 1 "launchctl cannot bootstrap the agent"
    assert_contains "$ERR" "could not enable $UPD_LABEL (launchctl exit 1); the hook is installed and scanning; fix the cause and run install --auto-update again" "the Linux shape"
    assert_eq "$(state_value auto_update)" yes "the state lets uninstall find the plist"
    assert_file "$(upd_plist)" "the plist is written"
    rm -f -- "$SANDBOX/launchctl.fail" || return 1
    gsg_from co install --auto-update
    assert_rc 0 "rerun once the cause is fixed"
}

