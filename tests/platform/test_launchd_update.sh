# ^ external the LaunchAgent is macOS only; its tests fake a Mac, and tools.lock and the file names on a Windows host do not fit that
if [ "$TEST_IS_WINDOWS" -eq 1 ]; then FILE_SKIP_REASON="macOS LaunchAgent, not a Windows feature"; fi

UPD_LABEL=com.lightspeeddms.git-secret-guard.update
DOC_LABEL=com.lightspeeddms.git-secret-guard.doctor
UPD_PLIST_MARKER='<!-- generated by git-secret-guard install auto-update; uninstall removes this file -->'
DOC_PLIST_MARKER='<!-- generated by git-secret-guard install with-timer; uninstall removes this file -->'
UPD_MARKER_LINE=3
UPD_INTERVAL_SECONDS=3600

upd_plist() { printf '%s' "$LC_HOME/Library/LaunchAgents/$UPD_LABEL.plist"; }
doc_plist() { printf '%s' "$LC_HOME/Library/LaunchAgents/$DOC_LABEL.plist"; }
upd_target() { printf 'gui/%s/%s' "$(id -u)" "$UPD_LABEL"; }
doc_target() { printf 'gui/%s/%s' "$(id -u)" "$DOC_LABEL"; }
launchctl_log() { if [ -f "$SANDBOX/launchctl.log" ]; then cat -- "$SANDBOX/launchctl.log"; fi; }

# ^ external the launchd path runs on the Darwin flow; on Linux a fake uname says Darwin, the plist text is the same
# ^ invariant a fresh macOS sandbox with fixtures and one checkout copy at $AU_CO (its real path, as install records it)
lau_begin() {
    lc_begin && as_macos && lc_make_fixtures && lc_use_fixtures && au_copy co git || return 1
    AU_CO="$(realpath -- "$SANDBOX/co")"
}

# ^ invariant lau_install [FLAG...] = lau_begin plus one install from the checkout copy, asserted to succeed
lau_install() {
    lau_begin || return 1
    gsg_from co install "$@"
    assert_rc 0 "install $*"
}

# ^ invariant a refusal leaves no state, share dir, tools or launchctl call behind
assert_lau_refused_untouched() {
    assert_no_file "$LC_STATE" "no state"
    assert_no_file "$LC_DATA" "no share dir"
    assert_no_file "$LC_BIN" "no tools"
    assert_eq "$(launchctl_log)" "" "launchctl was not called"
}

test_install_auto_update_on_macos_writes_a_marked_update_plist_and_bootstraps_it() {
    local p text bash_bin
    lau_install --auto-update || return 1
    p="$(upd_plist)"
    text="$(<"$p")"
    bash_bin="$(sed -n 's/^BASH_BIN=//p' "$LC_DATA/settings")"
    assert_eq "$(sed -n "${UPD_MARKER_LINE}p" "$p")" "$UPD_PLIST_MARKER" "the plist carries its own marker"
    assert_contains "$text" $'<key>Label</key>\n    <string>'"$UPD_LABEL"$'</string>' "the update label"
    assert_contains "$text" $'<array>\n        <string>'"$bash_bin"$'</string>\n        <string>'"$LC_DATA"$'/bin/git-secret-guard</string>\n        <string>update</string>\n    </array>' "recorded bash, installed CLI, update"
    assert_contains "$text" $'<key>StartInterval</key>\n    <integer>'"$UPD_INTERVAL_SECONDS"$'</integer>' "hourly"
    assert_not_contains "$text" "StartCalendarInterval" "no calendar schedule"
    assert_contains "$text" $'<key>StandardOutPath</key>\n    <string>'"$LC_STATE"$'/update.log</string>' "stdout goes to the update log in the state dir"
    assert_contains "$text" $'<key>StandardErrorPath</key>\n    <string>'"$LC_STATE"$'/update.log</string>' "and stderr too"
    assert_eq "$(launchctl_log)" "print $(upd_target)"$'\n'"bootstrap gui/$(id -u) $p" "loaded into the user's gui domain"
}

test_install_auto_update_records_the_state_and_loads_only_the_update_agent() {
    lau_install --auto-update || return 1
    assert_eq "$(state_value auto_update)" yes "the state records auto-update"
    assert_eq "$(state_value source_checkout)" "$AU_CO" "and the checkout install ran from"
    assert_eq "$(state_value timer_installed)" no "the doctor agent was not asked for"
    assert_no_file "$(doc_plist)" "no doctor plist without --with-timer"
    assert_no_file "$LC_HOME/.config" "no systemd directory"
    assert_contains "$(<"$LC_DATA/settings")" "LAUNCHCTL_BIN=$SANDBOX/pathbin/launchctl" "the settings record launchctl for uninstall"
    assert_not_contains "$OUT" "loginctl" "no linger hint on macOS"
    assert_contains "$OUT" "auto-update timer enabled ($(upd_plist)); read its output with: cat $LC_STATE/update.log" "the summary has the Linux shape, with the log as the hint"
    assert_no_file "$LC_STATE/update.lock" "the update lock is released"
}

test_the_test_interval_knob_is_announced_and_written_as_start_interval() {
    local text
    lau_begin || return 1
    set_env GSG_TEST_UPDATE_INTERVAL_SECONDS=20
    gsg_from co install --auto-update
    assert_rc 0 "install --auto-update with the knob"
    assert_contains "$ERR" "TEST OVERRIDE active (GSG_TEST_UPDATE_INTERVAL_SECONDS=[20])" "announced on stderr"
    text="$(<"$(upd_plist)")"
    assert_contains "$text" $'<key>StartInterval</key>\n    <integer>20</integer>' "the interval is the test value"
    assert_contains "$text" $'<key>GSG_TEST_UPDATE_INTERVAL_SECONDS</key>\n        <string>20</string>' "and the child install of an update run keeps it"
}

test_both_flags_install_two_separate_agents() {
    local uid
    lau_install --auto-update --with-timer || return 1
    uid="$(id -u)"
    assert_eq "$(sed -n "${UPD_MARKER_LINE}p" "$(upd_plist)")" "$UPD_PLIST_MARKER" "the update plist has its marker"
    assert_eq "$(sed -n "${UPD_MARKER_LINE}p" "$(doc_plist)")" "$DOC_PLIST_MARKER" "the doctor plist has its own"
    assert_eq "$(launchctl_log)" "print $(doc_target)"$'\n'"bootstrap gui/$uid $(doc_plist)"$'\n'"print $(upd_target)"$'\n'"bootstrap gui/$uid $(upd_plist)" "each agent is looked up and loaded once, nothing is booted out"
    assert_eq "$(state_value timer_installed)" yes "the doctor agent is recorded"
    assert_eq "$(state_value auto_update)" yes "and auto-update"
}

test_uninstall_boots_out_and_removes_the_update_agent_its_log_and_the_record() {
    lau_install --auto-update || return 1
    printf 'update output\n' >"$LC_STATE/update.log" || return 1
    printf 'an earlier log\n' >"$LC_STATE/update.log.1" || return 1
    printf 'result=current\n' >"$LC_STATE/update" || return 1
    : >"$SANDBOX/launchctl.log"
    gsg uninstall
    assert_rc 0 "uninstall"
    assert_eq "$(launchctl_log)" "print $(upd_target)"$'\n'"bootout $(upd_target)" "the update agent is booted out"
    assert_no_file "$(upd_plist)" "the plist is removed"
    assert_no_file "$LC_STATE/update.log" "and the log"
    assert_no_file "$LC_STATE/update.log.1" "and the one previous log the rotation keeps"
    assert_no_file "$LC_STATE/update" "and the update record"
    assert_no_file "$LC_STATE/state" "and the state"
    assert_no_file "$LC_DATA" "and the share dir"
    assert_contains "$OUT" "unloaded and removed the auto-update timer" "reported"
}

test_uninstall_removes_both_agents_when_both_were_installed() {
    lau_install --auto-update --with-timer || return 1
    : >"$SANDBOX/launchctl.log"
    gsg uninstall
    assert_rc 0 "uninstall"
    assert_eq "$(launchctl_log)" "print $(upd_target)"$'\n'"bootout $(upd_target)"$'\n'"print $(doc_target)"$'\n'"bootout $(doc_target)" "the update agent first, then the doctor agent"
    assert_no_file "$(upd_plist)" "update plist removed"
    assert_no_file "$(doc_plist)" "doctor plist removed"
}

test_uninstall_leaves_a_foreign_update_plist_alone() {
    lau_install --auto-update || return 1
    printf 'not ours\n' >"$(upd_plist)" || return 1
    printf 'output of a run\n' >"$LC_STATE/update.log" || return 1
    : >"$SANDBOX/launchctl.log"
    gsg uninstall
    assert_rc 0 "uninstall"
    assert_contains "$ERR" "$(upd_plist) was not written by git-secret-guard; left in place" "reported"
    assert_eq "$(<"$(upd_plist)")" "not ours" "and kept"
    assert_not_contains "$(launchctl_log)" "bootout" "a plist that is not ours is not unloaded"
    assert_file "$LC_STATE/update.log" "the update log stays: the agent step owns it on macOS"
}

test_a_foreign_plist_at_the_update_label_refuses_install_before_any_change() {
    lau_begin || return 1
    mkdir -p -- "$(dirname -- "$(upd_plist)")" && printf 'not ours\n' >"$(upd_plist)" || return 1
    gsg_from co install --auto-update
    assert_rc 1 "a foreign plist at the update label"
    assert_contains "$ERR" "$(upd_plist) exists and was not written by git-secret-guard; move it away and run install again; nothing was changed" "says whose it is"
    assert_eq "$(<"$(upd_plist)")" "not ours" "the file is untouched"
    assert_lau_refused_untouched
}

