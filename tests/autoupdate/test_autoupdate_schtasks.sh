}

test_install_auto_update_registers_one_hourly_task_that_runs_the_wrapper() {
    local lw
    sch_install
    assert_rc 0 "install --auto-update"
    assert_eq "$(state_value auto_update)" yes "the state says auto_update=yes"
    assert_eq "$(state_value source_checkout)" "$AU_CO" "and records the checkout"
    assert_eq "$(sch_calls /Create)" 1 "one task is created"
    assert_contains "$(sch_log)" "/Create /TN $SCH_NAME /SC HOURLY /TR \"$(sch_win "$(sch_cmd)")\" /F" "an hourly task, /F, the wrapper as its action"
    assert_not_contains "$(sch_log)" "/MO" "no repetition knob: the schedule is the plain hour"
    assert_file "$(sch_cmd)" "the wrapper is in the state dir, outside the share"
    assert_eq "$(sed -n 2p "$(sch_cmd)" | tr -d '\r')" "$SCH_MARKER" "line 2 of the wrapper is its marker"
    lw="$(sch_win "$LC_STATE/update.log")"
    assert_contains "$(<"$(sch_cmd)")" "update >> \"$lw\" 2>&1" "stdout and stderr of update are appended to the log in the state dir"
    assert_contains "$(<"$(sch_cmd)")" "if exist \"$lw\" for %%F in (\"$lw\") do if %%~zF GTR $SCH_LOG_MAX move /y \"$lw\" \"$lw.1\" >nul 2>&1" "a long log is moved aside after the run"
    assert_contains "$(<"$(sch_cmd)")" "$(cygpath -m "$LC_DATA")/bin/git-secret-guard\" update" "it runs the installed CLI with update"
    assert_contains "$(<"$(sch_cmd)")" "set \"XDG_DATA_HOME=$SANDBOX/xdg/data\"" "and carries the XDG variables this install ran with"
    assert_contains "$OUT" "auto-update task registered ($SCH_NAME, every hour)" "install says so"
    assert_contains "$OUT" "$LC_STATE/update.log" "and where the output goes"
    assert_contains "$(<"$LC_DATA/settings")" "SCHTASKS_BIN=" "the settings record the absolute schtasks path"
    assert_not_contains "$(<"$LC_DATA/settings")" "SYSTEMCTL_BIN" "and no systemctl"
    assert_eq "$(systemctl_log)" "" "systemctl is never called"
}

