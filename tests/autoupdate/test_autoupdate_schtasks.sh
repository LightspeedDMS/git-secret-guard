# ^ hazard cmd resumes a rewritten wrapper at the byte offset it saved; the v1.1.1 wrapper rewritten by the child install of the first update to this version
# ^ invariant the old wrapper is built from the new text by the inverse change; its update line rewrites the wrapper and exits 3, counting its runs
test_a_wrapper_rewritten_while_cmd_runs_it_runs_update_once_and_keeps_its_status() {
    local new head
    sch_install
    assert_rc 0 "install --auto-update"
    new="$(<"$(sch_cmd)")"
    cp -- "$(sch_cmd)" "$SANDBOX/new-wrapper.cmd" || return 1
    head="${new%%set \"GSG_RC=*}"
    { printf '%s' "${head/ update >> / update > }"; printf 'exit /b %%errorlevel%%\r\n'; } >"$(sch_cmd)" || return 1
    assert_not_contains "$(<"$(sch_cmd)")" "GSG_RC" "the wrapper on disk is the old one"
    : >"$SANDBOX/probe.count"
    sch_probe_cli 3 "echo run >>\"$SANDBOX/probe.count\"" "cp -- \"$SANDBOX/new-wrapper.cmd\" \"$LC_STATE/.swap\" && mv -f -- \"$LC_STATE/.swap\" \"$(sch_cmd)\"" || return 1
    run_cap env -i "${LC_ENV[@]}" "${EXTRA_ENV[@]}" cmd //c "$(sch_win "$(sch_cmd)")" </dev/null
    assert_rc 3 "the transition run keeps the status of update"
    assert_eq "$(wc -l <"$SANDBOX/probe.count" | tr -d ' ')" 1 "update ran once, not again from the new text"
    assert_contains "$(<"$(sch_cmd)")" "GSG_RC" "and the wrapper on disk is the new one"
    assert_not_contains "$OUT$ERR" "not recognized" "cmd ran no half line"
}

# ^ invariant sch_log_runs FILE N LABEL = FILE holds exactly N runs, a start line each, and every line starts with a UTC stamp
sch_log_runs() {
    local line starts=0
    local -a lines=()
    mapfile -t lines <"$1" || return 1
    for line in "${lines[@]}"; do
        line="${line%$'\r'}"
        [[ $line =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z\  ]] || fail "$3: a line is not stamped: [$line]"
        if [[ $line == *"update: run started, "* ]]; then starts=$((starts + 1)); fi
    done
    assert_eq "$starts" "$2" "$3"
}

