SCH_NAME="$(sed -n 's/^GSG_UPDATE_TASK_NAME=//p' "$GSG_PROJECT/lib/core/state.sh")"
SCH_MARKER='rem generated by git-secret-guard install --auto-update; uninstall removes this file'
# ^ coupled lib/autoupdate/autoupdate.sh:GSG_UPDATE_LOG_MAX; the wrapper moves a log of more bytes than this to update.log.1
SCH_LOG_MAX=1048576

sch_cmd() { printf '%s' "$LC_STATE/update-task.cmd"; }
sch_log() { if [ -f "$SANDBOX/schtasks.log" ]; then cat -- "$SANDBOX/schtasks.log"; fi; }
sch_win() { cygpath -w "$1"; }
sch_calls() { sch_log | grep -c "^$1 " || true; }

# ^ invariant sch_install = au_begin plus one install --auto-update from the checkout copy; the caller asserts the exit status
sch_install() {
    au_begin || return 1
