# ^ invariant the git dir comes first, followed by /usr/local/bin:/usr/bin:/bin, each directory once, in order
test_the_unit_path_has_no_duplicate_entries() {
    local want
    timer_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer"
    case "$(lc_first_git_dir)" in
        /usr/local/bin) want=/usr/local/bin:/usr/bin:/bin ;;
        /usr/bin) want=/usr/bin:/usr/local/bin:/bin ;;
        *) fail "the first git is in [$(lc_first_git_dir)], this test knows /usr/local/bin and /usr/bin"; return 1 ;;
    esac
    assert_contains "$(<"$(unit_dir)/$SERVICE")" $'\nEnvironment="PATH='"$want"$'"\n' "the git dir is not repeated"
    # shellcheck disable=SC2016
    run_cap env -i bash -c 'GSG_SHARE=/x; source "$1/lib/timer.sh" && timer_service_text "$2"' _ "$GSG_PROJECT" /usr/bin
    assert_rc 0 "timer_service_text with the git in /usr/bin"
    assert_contains "$OUT" $'\nEnvironment="PATH=/usr/bin:/usr/local/bin:/bin"\n' "a later duplicate is dropped, the order is kept"
    # shellcheck disable=SC2016
    run_cap env -i bash -c 'GSG_SHARE=/x; source "$1/lib/timer.sh" && timer_service_text "$2"' _ "$GSG_PROJECT" /opt/git/bin
    assert_contains "$OUT" $'\nEnvironment="PATH=/opt/git/bin:/usr/local/bin:/usr/bin:/bin"\n' "another directory goes first and the rest follow"
}

# ^ external the user manager drops the login environment; a custom XDG dir or GIT_CONFIG_GLOBAL at install time is invisible to the timer's doctor
test_the_service_carries_the_xdg_and_git_config_variables_set_at_install_time() {
    local svc
    local -a unit_env=()
    timer_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer"
    svc="$(<"$(unit_dir)/$SERVICE")"
    assert_contains "$svc" $'\nEnvironment="XDG_DATA_HOME='"$SANDBOX"$'/xdg/data"\n' "the data dir"
    assert_contains "$svc" $'\nEnvironment="XDG_STATE_HOME='"$SANDBOX"$'/xdg/state"\n' "the state dir"
    assert_contains "$svc" $'\nEnvironment="GIT_CONFIG_GLOBAL='"$SANDBOX"$'/gitconfig"\n' "the global git config"
    assert_not_contains "$svc" "XDG_CONFIG_HOME" "a variable that was not set is not written"
    mapfile -t unit_env < <(sed -n 's/^Environment="\(.*\)"$/\1/p' "$(unit_dir)/$SERVICE") || return 1
    # ^ external a Mac has no systemd and the unit's Linux PATH holds no bash >= 4.4; the XDG and git variables this test is about stay as the unit wrote them
    if [ "$TEST_OS" = Darwin ]; then unit_env+=(PATH="$SANDBOX/pathbin:$TEST_BASE_PATH"); fi
    mkdir -p -- "$SANDBOX/emptyroot" || return 1
    run_cap env -i HOME="$LC_HOME" "${unit_env[@]}" "$LC_DATA/bin/git-secret-guard" doctor --roots "$SANDBOX/emptyroot"
    assert_contains "$OUT" "ok       installed: version " "the unit's own environment finds the install"
    assert_not_contains "$OUT" "not installed" "and does not report it as missing"
    set_env XDG_CONFIG_HOME="$SANDBOX/xdgcfg"
    gsg install --with-timer
    assert_rc 0 "install --with-timer with a custom config dir"
    assert_contains "$(<"$SANDBOX/xdgcfg/systemd/user/$SERVICE")" $'\nEnvironment="XDG_CONFIG_HOME='"$SANDBOX"$'/xdgcfg"\n' "XDG_CONFIG_HOME when it was set"
}

