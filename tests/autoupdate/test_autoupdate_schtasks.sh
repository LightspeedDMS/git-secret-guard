test_status_and_doctor_read_files_only_and_say_hourly() {
    sch_install
    assert_rc 0 "install --auto-update"
    printf 'checked_at=%s\nrole=owner\nresult=skipped\nreason=dirty\ndetail=\nfrom=%s\nto=\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(<"$AU_CO/VERSION")" >"$LC_STATE/update" || return 1
    : >"$SANDBOX/schtasks.log"
    gsg_installed status
    assert_contains "$OUT" "auto-update: on (checkout $AU_CO, every 1h)" "the on line with the fixed hour"
    assert_contains "$OUT" "last check:" "the last check comes from the record"
    mkdir -p -- "$SANDBOX/roots"
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_not_contains "$OUT" "auto-update: timer inactive" "a wrapper that is ours and a fresh record: no finding"
    assert_not_contains "$OUT" "linger" "no linger warning on Windows"
    assert_contains "$OUT" "auto-update: on, following $AU_CO every 1h" "the ok line"
    assert_eq "$(sch_log)" "" "status and doctor never run schtasks"
    rm -f -- "$(sch_cmd)" || return 1
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_contains "$OUT" "auto-update: timer inactive: $(sch_cmd) is missing" "a missing wrapper is a PROBLEM that names it"
    assert_eq "$(sch_log)" "" "still no schtasks"
}

test_a_stale_record_is_a_problem_and_a_missing_one_is_judged_by_the_wrapper_age() {
    sch_install
    assert_rc 0 "install --auto-update"
    printf 'checked_at=2000-01-01T00:00:00Z\nrole=owner\nresult=current\nreason=\ndetail=\nfrom=%s\nto=\n' "$(<"$AU_CO/VERSION")" >"$LC_STATE/update" || return 1
    mkdir -p -- "$SANDBOX/roots"
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_contains "$OUT" "auto-update: timer inactive: the last check was at 2000-01-01T00:00:00Z" "an old record"
    assert_contains "$OUT" "$LC_STATE/update.log" "the hint names the log, not journalctl"
    rm -f -- "$LC_STATE/update" || return 1
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_contains "$OUT" "no update run is recorded yet" "a wrapper written just now has not had to run yet"
    touch -d '2000-01-01 00:00:00' "$(sch_cmd)" || return 1
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_contains "$OUT" "auto-update: timer inactive: no update run is recorded" "a wrapper written long ago and no record"
}

