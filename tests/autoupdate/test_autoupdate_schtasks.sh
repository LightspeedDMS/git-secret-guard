# shellcheck shell=bash disable=SC2016
# ^ invariant install --auto-update, update's task, status, doctor, uninstall on Windows; schtasks is the stand-in of tests/support/lifecycle.sh
# ^ security no test here registers a real task; the stand-in is first on PATH and install records its absolute path for uninstall
# shellcheck source=tests/support/lib.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/../support/lib.sh"
# shellcheck source=tests/support/lifecycle.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/../support/lifecycle.sh"
# shellcheck source=tests/support/autoupdate_units.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/../support/autoupdate_units.sh"

# ^ external the flow runs the Windows branches of install (cygpath, native git); Linux has systemd units, see tests/autoupdate/test_autoupdate_units.sh
if [ "$TEST_IS_WINDOWS" -ne 1 ]; then FILE_SKIP_REASON="Windows only: install --auto-update registers a Task Scheduler task there; Linux has systemd units (test_autoupdate_units)"; fi

# ^ invariant read from the library, never typed here => no test names the product's task by hand
SCH_NAME="$(sed -n 's/^GSG_UPDATE_TASK_NAME=//p' "$GSG_PROJECT/lib/core/state.sh")"
SCH_MARKER='rem generated by git-secret-guard install --auto-update; uninstall removes this file'

sch_cmd() { printf '%s' "$LC_STATE/update-task.cmd"; }
sch_log() { if [ -f "$SANDBOX/schtasks.log" ]; then cat -- "$SANDBOX/schtasks.log"; fi; }
sch_win() { cygpath -w "$1"; }
sch_calls() { sch_log | grep -c "^$1 " || true; }

# ^ invariant sch_install = au_begin plus one install --auto-update from the checkout copy; the caller asserts the exit status
sch_install() {
    au_begin || return 1
    gsg_from co install --auto-update
}

test_install_auto_update_registers_one_hourly_task_that_runs_the_wrapper() {
    sch_install
    assert_rc 0 "install --auto-update"
    assert_eq "$(state_value auto_update)" yes "the state says auto_update=yes"
    assert_eq "$(state_value source_checkout)" "$AU_CO" "and records the checkout"
    assert_eq "$(sch_calls /Create)" 1 "one task is created"
    assert_contains "$(sch_log)" "/Create /TN $SCH_NAME /SC HOURLY /TR \"$(sch_win "$(sch_cmd)")\" /F" "an hourly task, /F, the wrapper as its action"
    assert_not_contains "$(sch_log)" "/MO" "no repetition knob: the schedule is the plain hour"
    assert_file "$(sch_cmd)" "the wrapper is in the state dir, outside the share"
    assert_eq "$(sed -n 2p "$(sch_cmd)" | tr -d '\r')" "$SCH_MARKER" "line 2 of the wrapper is its marker"
    assert_contains "$(<"$(sch_cmd)")" "update > \"$(sch_win "$LC_STATE/update.log")\" 2>&1" "stdout and stderr of update go to the log in the state dir"
    assert_contains "$(<"$(sch_cmd)")" "$(cygpath -m "$LC_DATA")/bin/git-secret-guard\" update" "it runs the installed CLI with update"
    assert_contains "$(<"$(sch_cmd)")" "set \"XDG_DATA_HOME=$SANDBOX/xdg/data\"" "and carries the XDG variables this install ran with"
    assert_contains "$OUT" "auto-update task registered ($SCH_NAME, every hour)" "install says so"
    assert_contains "$OUT" "$LC_STATE/update.log" "and where the output goes"
    assert_contains "$(<"$LC_DATA/settings")" "SCHTASKS_BIN=" "the settings record the absolute schtasks path"
    assert_not_contains "$(<"$LC_DATA/settings")" "SYSTEMCTL_BIN" "and no systemctl"
    assert_eq "$(systemctl_log)" "" "systemctl is never called"
}

