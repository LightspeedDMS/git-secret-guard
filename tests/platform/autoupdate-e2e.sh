MARKER='# generated by git-secret-guard install --auto-update; uninstall removes this file'
INTERVAL=20
# ^ external the timer has no AccuracySec, systemd may fire it up to a minute late => one run is awaited for this long
RUN_BOUND=120
# ^ external OnBootSec=5min counts from the boot of the container; the first run after enable --now comes 5 minutes after it (observed)
FIRST_RUN_BOUND=420
# ^ invariant no wait goes on past this many seconds of the script => a product bug costs a few bounds, never the launcher's whole timeout
# ^ coupled tests/platform/autoupdate.sh:TOTAL_TIMEOUT_SECONDS is larger
E2E_DEADLINE=2100
