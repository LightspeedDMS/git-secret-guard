# ^ invariant a task starts with the logon profile HOME; the wrapper sets the HOME of the install, or the child install writes the CLI link of another profile
# ^ why through real cmd and bash.exe, not a text check; only a run shows the value reads back as the same POSIX path
test_the_wrapper_gives_bash_the_home_of_the_install() {
    local probe="$LC_STATE/home-probe.cmd" bash_win
    sch_install
    assert_rc 0 "install --auto-update"
    assert_contains "$(<"$(sch_cmd)")" 'set "HOME=' "the wrapper sets HOME"
    bash_win="$(cygpath -m /)" || return 1
    mkdir -p -- "$SANDBOX/other-profile" || return 1
    { printf '@echo off\r\n'; grep '^set ' "$(sch_cmd)"; printf '"%sbin/bash.exe" -c "echo $HOME"\r\n' "${bash_win%/}/"; } >"$probe" || return 1
    run_cap env -i "${LC_ENV[@]}" "${EXTRA_ENV[@]}" HOME="$SANDBOX/other-profile" cmd //c "$(sch_win "$probe")" </dev/null
    assert_rc 0 "the probe ran"
    assert_eq "$(tr -d '\r' <<<"$OUT")" "$LC_HOME" "bash reads the install's HOME back as the same POSIX path, not the profile's"
    rm -f -- "$probe"
}

