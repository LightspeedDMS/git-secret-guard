# ^ external launchd cannot run in a test; the plist's program, arguments and environment run under env -i, stdout and stderr in the file StandardOutPath names
# ^ invariant leaves RC set to the doctor run's status; asserts the log is $LC_STATE/doctor.log and the last argument is doctor
run_agent_like_launchd() {
    local key
    local -A v=()
    for key in StandardOutPath EnvironmentVariables.PATH EnvironmentVariables.XDG_DATA_HOME EnvironmentVariables.XDG_STATE_HOME \
        EnvironmentVariables.GIT_CONFIG_GLOBAL ProgramArguments.0 ProgramArguments.1 ProgramArguments.2; do
        run_cap plutil -extract "$key" raw -o - "$(plist_path)"
        assert_rc 0 "the plist carries $key"
        v[$key]="$OUT"
    done
    assert_eq "${v[StandardOutPath]}" "$LC_STATE/doctor.log" "the log is in the state dir"
    assert_eq "${v[ProgramArguments.2]}" doctor "the last argument is the doctor command"
    # shellcheck disable=SC2016
    run_cap bash -c 'log="$1"; shift; exec >"$log" 2>&1; exec env -i "$@"' _ "${v[StandardOutPath]}" HOME="$LC_HOME" PATH="${v[EnvironmentVariables.PATH]}" \
        XDG_DATA_HOME="${v[EnvironmentVariables.XDG_DATA_HOME]}" XDG_STATE_HOME="${v[EnvironmentVariables.XDG_STATE_HOME]}" \
        GIT_CONFIG_GLOBAL="${v[EnvironmentVariables.GIT_CONFIG_GLOBAL]}" "${v[ProgramArguments.0]}" "${v[ProgramArguments.1]}" "${v[ProgramArguments.2]}"
}

test_the_agent_command_runs_doctor_and_its_output_lands_in_the_log() {
    install_agent_for_run || return 1
    run_agent_like_launchd
    assert_file "$LC_STATE/doctor.log" "the log exists"
    assert_contains "$(<"$LC_STATE/doctor.log")" "machine:" "the doctor report is in the log"
    assert_contains "$(<"$LC_STATE/doctor.log")" "summary:" "the doctor report reaches its summary line"
}

test_the_weekly_agent_run_writes_the_findings_record() {
    local record
    install_agent_for_run || return 1
    record="$LC_STATE/findings"
    chmod -x "$LC_DATA/hooks/secret-scan" || return 1
    run_agent_like_launchd
    assert_rc 1 "the agent's doctor run reports the broken hook command"
    assert_file "$record" "the agent's run wrote the findings record"
    assert_eq "$(sed -n 1p "$record")" "git-secret-guard findings 1" "a valid record header"
    assert_contains "$(tail -n +3 "$record")" "machine"$'\t'"hook: hook command is missing or not executable ($LC_DATA/hooks/secret-scan)" "the PROBLEM doctor printed is in the record"
    assert_contains "$(<"$LC_STATE/doctor.log")" "hook command is missing or not executable" "and in the agent's log"
    chmod +x "$LC_DATA/hooks/secret-scan" || return 1
    run_agent_like_launchd
    assert_rc 0 "the next weekly run is clean once the hook command is back"
    assert_file "$record" "the record still exists after the clean run"
    assert_eq "$(tail -n +3 "$record")" "" "and is empty"
}

