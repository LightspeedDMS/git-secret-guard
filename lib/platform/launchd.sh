# shellcheck shell=bash disable=SC2153,SC2034
# ^ coupled CLI-only library, sourced after timer.sh; the hook never loads it (test:test_the_hook_never_loads_the_doctor_and_timer_libraries)

# ^ coupled GSG_LAUNCHD_LABEL lives in lib/core/state.sh next to the paths built from it
# ^ external an XML comment holds no double hyphen, hence a marker of its own, not GSG_TIMER_MARKER (it names install --with-timer)
# ^ external plistlib rejects a comment ahead of the DOCTYPE and launchd parses with libxpc, not CoreFoundation; standard header, marker on line 3
GSG_LAUNCHD_XML_DECL='<?xml version="1.0" encoding="UTF-8"?>'
GSG_LAUNCHD_DOCTYPE='<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">'
GSG_LAUNCHD_MARKER='<!-- generated by git-secret-guard install with-timer; uninstall removes this file -->'
GSG_LAUNCHD_UPDATE_MARKER='<!-- generated by git-secret-guard install auto-update; uninstall removes this file -->'

# ^ invariant sets LJ_* for one job, $1 = doctor (--with-timer, the default) or update (--auto-update); LJ_ENV = the extra variable names the job passes on
# ^ why one table, not two copies of every function; both jobs share the plist, load and unload code and differ in these values and the schedule
launchd_job_set() {
    case "${1:-doctor}" in
        doctor)
            LJ_JOB=doctor LJ_FLAG=--with-timer LJ_LONG='weekly doctor agent' LJ_VERB=load LJ_LABEL="$GSG_LAUNCHD_LABEL" LJ_PLIST="$GSG_AGENT_PLIST"
            LJ_LOG="$GSG_AGENT_LOG" LJ_MARKER="$GSG_LAUNCHD_MARKER" LJ_ENV=()
            ;;
        update)
            LJ_JOB=update LJ_FLAG=--auto-update LJ_LONG='auto-update timer' LJ_VERB=enable LJ_LABEL="$GSG_LAUNCHD_UPDATE_LABEL" LJ_PLIST="$GSG_UPDATE_AGENT_PLIST"
            LJ_LOG="$GSG_UPDATE_AGENT_LOG" LJ_MARKER="$GSG_LAUNCHD_UPDATE_MARKER" LJ_ENV=("${GSG_UPDATE_ENV_NAMES[@]}")
            ;;
        *)
            printf '%s: internal error: unknown launchd job [%s]\n' "$GSG_NAME" "$1" >&2
            return 1
            ;;
    esac
}

# ^ invariant prints one <string> element indented by $1 spaces, the value in $2 XML-escaped; & goes first => no entity is escaped twice
# ^ external bash 5.2 expands an unquoted & in a replacement to the matched text (patsub_replacement); the replacements are quoted
launchd_string() {
    local v="$2"
    v="${v//&/"&amp;"}"
    v="${v//</"&lt;"}"
    v="${v//>/"&gt;"}"
    v="${v//\"/"&quot;"}"
    printf '%*s<string>%s</string>\n' "$1" "" "$v"
}

# ^ invariant true only for a regular file (never a link) with the xml declaration on line 1 and the marker on line 3 => only a plist install wrote
# ^ invariant $2 = the marker of the job, the doctor agent's when absent
launchd_plist_is_ours() {
    local decl="" doctype="" marker=""
    if [ ! -f "$1" ] || [ -L "$1" ]; then return 1; fi
    { IFS= read -r decl && IFS= read -r doctype && IFS= read -r marker; } <"$1" || true
    [ "$decl" = "$GSG_LAUNCHD_XML_DECL" ] && [ "$marker" = "${2:-$GSG_LAUNCHD_MARKER}" ]
}

# ^ why refuse control characters, not escape them; XML 1.0 cannot carry them at all, and escaping the rest (& < > ") is exact
# ^ invariant $1 = the directory of the git install found first; the bash path is the recorded one, or the Homebrew one before install has placed it
# ^ invariant $2 = doctor (the default) or update; the job's extra variables (LJ_ENV) are checked like the standing ones
launchd_check_values() {
    local what n
    launchd_job_set "${2:-doctor}" || return 1
    local -a values=("$GSG_SHARE" "$GSG_AGENT_DIR" "$LJ_LOG" "${INSTALL_BASH_BIN:-${BREW_BASH:-}}" "$1")
    timer_check_config_global || return 1
    for n in "${GSG_TIMER_ENV_NAMES[@]}" "${LJ_ENV[@]}"; do
        if [ -n "${!n:-}" ]; then values+=("${!n}"); fi
    done
    if [ "$LJ_JOB" = update ]; then
        for n in "${GSG_UPDATE_PATH_NAMES[@]}"; do
            if [ -n "${!n:-}" ]; then values+=("${!n}"); fi
        done
    fi
    for what in "${values[@]}"; do
        case "$what" in
            *[[:cntrl:]]*)
                printf '%s: %s cannot be written into a launchd plist (it holds a control character); %s\n' "$GSG_NAME" "${what//[[:cntrl:]]/?}" "$(brew_unchanged_text)" >&2
                return 1
                ;;
        esac
    done
}

# ^ external StartCalendarInterval Weekday 1 = Monday; launchd runs one missed slot after wake, like Persistent=true in the systemd timer
GSG_LAUNCHD_WEEKDAY=1
GSG_LAUNCHD_HOUR=10
GSG_LAUNCHD_MINUTE=0
GSG_LAUNCHD_RETRY_SECONDS=1

# ^ invariant $1 = the git directory, $2 = doctor (the default) or update
launchd_check_target() {
    launchd_check_values "$1" "${2:-doctor}" || return 1
    if { [ -e "$LJ_PLIST" ] || [ -L "$LJ_PLIST" ]; } && ! launchd_plist_is_ours "$LJ_PLIST" "$LJ_MARKER"; then
        printf '%s: %s exists and was not written by git-secret-guard; move it away and run install again; %s\n' "$GSG_NAME" "$LJ_PLIST" "$(brew_unchanged_text)" >&2
        return 1
    fi
}

# ^ external launchd starts an agent with a bare environment; PATH is the one the unit gets (git install first) and the set XDG and git variables follow
launchd_env_entries() {
    local n path
    if [ "$LJ_JOB" = update ]; then
        timer_update_path "$1" || return 1
        path="$REPLY"
    else
        path="$(timer_unit_path "$1")"
    fi
    printf '%s\n' '    <key>EnvironmentVariables</key>' '    <dict>' '        <key>PATH</key>'
    launchd_string 8 "$path"
    for n in "${GSG_TIMER_ENV_NAMES[@]}" "${LJ_ENV[@]}"; do
        if [ -z "${!n:-}" ]; then continue; fi
        printf '        <key>%s</key>\n' "$n"
        launchd_string 8 "${!n}"
    done
    printf '%s\n' '    </dict>'
}

launchd_log_entry() {
    printf '    <key>%s</key>\n' "$1"
    launchd_string 4 "$LJ_LOG"
}

# ^ invariant prints the schedule keys of the job set by launchd_job_set; the update job runs every N seconds, the doctor job weekly
launchd_schedule() {
    if [ "$LJ_JOB" = update ]; then
        if ! timer_interval_seconds "${INSTALL_UPDATE_INTERVAL:-}"; then
            printf '%s: internal error: update interval [%s] is not 1h or <n>s\n' "$GSG_NAME" "${INSTALL_UPDATE_INTERVAL:-}" >&2
            return 1
        fi
        printf '%s\n' '    <key>StartInterval</key>' "    <integer>$REPLY</integer>" '    <key>RunAtLoad</key>' '    <true/>'
        return 0
    fi
    printf '%s\n' '    <key>StartCalendarInterval</key>' '    <dict>' \
        '        <key>Weekday</key>' "        <integer>$GSG_LAUNCHD_WEEKDAY</integer>" \
        '        <key>Hour</key>' "        <integer>$GSG_LAUNCHD_HOUR</integer>" \
        '        <key>Minute</key>' "        <integer>$GSG_LAUNCHD_MINUTE</integer>" '    </dict>'
}

# ^ invariant $1 = the git directory for PATH; the text is the whole file, the xml declaration on line 1 and the marker comment on line 3
# ^ invariant describes the job set by launchd_job_set; rc 1 = the schedule cannot be written, the caller must not use the partial text
launchd_plist_text() {
    printf '%s\n' "$GSG_LAUNCHD_XML_DECL" "$GSG_LAUNCHD_DOCTYPE" "$LJ_MARKER" \
        '<plist version="1.0">' '<dict>' '    <key>Label</key>'
    launchd_string 4 "$LJ_LABEL"
    printf '%s\n' '    <key>ProgramArguments</key>' '    <array>'
    launchd_string 8 "${INSTALL_BASH_BIN:-${BREW_BASH:-}}"
    launchd_string 8 "$GSG_SHARE/bin/git-secret-guard"
    launchd_string 8 "$LJ_JOB"
    printf '%s\n' '    </array>'
    launchd_schedule || return 1
    launchd_env_entries "$1" || return 1
    launchd_log_entry StandardOutPath
    launchd_log_entry StandardErrorPath
    printf '%s\n' '</dict>' '</plist>'
}

# ^ invariant sets REPLY = the numeric uid of the user; the gui/<uid> domain is where a LaunchAgent of this user lives
launchd_uid() {
    REPLY="$(id -u)" || {
        printf '%s: cannot read the user id (id -u failed); the hook is installed and scanning\n' "$GSG_NAME" >&2
        return 1
    }
}

# ^ why create the state dir here, not leave it to launchd; launchd opens the log file named in the plist and never makes the directory above it
# ^ invariant $1 = the whole plist text; it appears complete or not at all (timer_write_unit renames a temp file)
launchd_write_plist() {
    mkdir -p -- "$GSG_AGENT_DIR" || {
        printf '%s: cannot create %s; the hook is installed and scanning\n' "$GSG_NAME" "$GSG_AGENT_DIR" >&2
        return 1
    }
    state_make_dir || {
        printf '%s: cannot create %s for the agent log; the hook is installed and scanning\n' "$GSG_NAME" "$GSG_STATE_DIR" >&2
        return 1
    }
    timer_write_unit "$LJ_PLIST" "$1" || {
        printf '%s: could not write %s; the hook is installed and scanning\n' "$GSG_NAME" "$LJ_PLIST" >&2
        return 1
    }
}

# ^ order install_run writes the state (timer_installed=yes or auto_update=yes) before this step => a failed load leaves a plist uninstall can find
# ^ why unload a loaded agent first, not bootstrap over it; bootstrap of a loaded label fails, and a reload reads a changed plist
# ^ invariant $1 = doctor (the default) or update; the plist text is made first, a failure to make it stops before any write
launchd_install_agent() {
    local uid target rc text
    launchd_job_set "${1:-doctor}" || return 1
    launchd_uid || return 1
    uid="$REPLY"
    target="gui/$uid/$LJ_LABEL"
    text="$(launchd_plist_text "${GSG_GIT%/*}")" || return 1
    launchd_write_plist "$text" || return 1
    if "$INSTALL_TIMER_BIN" print "$target" >/dev/null 2>&1; then
        "$INSTALL_TIMER_BIN" bootout "$target" || {
            printf '%s: could not unload the loaded agent %s; the hook is installed and scanning; run launchctl bootout %s and install %s again\n' \
                "$GSG_NAME" "$LJ_LABEL" "$target" "$LJ_FLAG" >&2
            return 1
        }
    fi
    "$INSTALL_TIMER_BIN" bootstrap "gui/$uid" "$LJ_PLIST"
    rc=$?
    if [ "$rc" -ne 0 ]; then
        # ^ why one retry after a bootout, not a loop; a bootstrap right after a bootout can fail until the old job is gone
        "$INSTALL_TIMER_BIN" bootout "$target" >/dev/null 2>&1 || :
        sleep "$GSG_LAUNCHD_RETRY_SECONDS"
        "$INSTALL_TIMER_BIN" bootstrap "gui/$uid" "$LJ_PLIST"
        rc=$?
    fi
    if [ "$rc" -ne 0 ]; then
        printf '%s: could not %s %s (launchctl exit %s); the hook is installed and scanning; fix the cause and run install %s again\n' \
            "$GSG_NAME" "$LJ_VERB" "$LJ_LABEL" "$rc" "$LJ_FLAG" >&2
        return 1
    fi
    if [ "$LJ_JOB" = update ]; then
        printf '%s: %s enabled (%s); read its output with: cat %s\n' "$GSG_NAME" "$LJ_LONG" "$LJ_PLIST" "$LJ_LOG"
    else
        printf '%s: %s loaded (%s); its output goes to %s\n' "$GSG_NAME" "$LJ_LONG" "$LJ_PLIST" "$LJ_LOG"
    fi
}

# ^ invariant rewrites the plist only when it is ours and its text changed; a foreign or missing plist is left alone and launchctl is not run
# ^ why only a hint for the reload, not the call; a plain install must work where launchctl is gone and must not load an agent the user unloaded
# ^ invariant $1 = doctor (the default) or update
launchd_refresh_agent() {
    local text
    launchd_job_set "${1:-doctor}" || return 1
    if ! launchd_check_values "${GSG_GIT%/*}" "$LJ_JOB" 2>/dev/null; then
        printf '%s: the %s was not refreshed: a path or variable cannot be written into a launchd plist; run install %s to see which\n' "$GSG_NAME" "$LJ_LONG" "$LJ_FLAG" >&2
        return 0
    fi
    if ! launchd_plist_is_ours "$LJ_PLIST" "$LJ_MARKER"; then return 0; fi
    text="$(launchd_plist_text "${GSG_GIT%/*}")" || return 1
    if [ "$(<"$LJ_PLIST")" = "$text" ]; then return 0; fi
    launchd_write_plist "$text" || return 1
    launchd_uid || return 1
    printf '%s: updated the %s %s; the agent is left as it was, run launchctl bootout gui/%s/%s and launchctl bootstrap gui/%s %s to reload it\n' \
        "$GSG_NAME" "$LJ_LONG" "$LJ_PLIST" "$REPLY" "$LJ_LABEL" "$REPLY" "$LJ_PLIST"
}

# ^ invariant $1 = doctor or update, $2 = 1 writes and loads the agent, 0 only refreshes a plist of ours; another value is refused
launchd_enable() {
    case "${2:-0}" in
        1) launchd_install_agent "$1" ;;
        0) launchd_refresh_agent "$1" ;;
        *)
            printf '%s: internal error: launchd_enable flag [%s] is not 0 or 1\n' "$GSG_NAME" "$2" >&2
            return 1
            ;;
    esac
}
