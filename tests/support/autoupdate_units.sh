#!/usr/bin/env bash
# shellcheck shell=bash disable=SC2034
# ^ order sourced after lib.sh and lifecycle.sh by tests/autoupdate/test_autoupdate_units.sh; every path stays inside the lifecycle sandbox

SERVICE=git-secret-guard-doctor.service
TIMER=git-secret-guard-doctor.timer
UPD_SERVICE=git-secret-guard-update.service
UPD_TIMER=git-secret-guard-update.timer
UPD_MARKER="# generated by git-secret-guard install --auto-update; uninstall removes this file"
# ^ coupled the read-only call install_prepare_update makes to see whether the user manager answers
PROBE_CALL="--user show --property=Version"
# ^ invariant the lock holder only has to outlive one test; au_drop_lock ends it sooner on every exit
AU_HOLDER_SECONDS=300
AU_HOLDER=""
AU_CO=""

unit_dir() { printf '%s' "$LC_HOME/.config/systemd/user"; }
# ^ invariant au_log NAME prints $SANDBOX/NAME.log, nothing when the stand-in never got far enough to write it
au_log() { if [ -f "$SANDBOX/$1.log" ]; then cat -- "$SANDBOX/$1.log"; fi; }
systemctl_log() { au_log systemctl; }
timeout_log() { au_log timeout; }
au_reset_systemctl_log() { : >"$SANDBOX/systemctl.log"; }
# ^ invariant au_fail_systemctl WORD makes the stand-in fail every call whose arguments hold WORD
au_fail_systemctl() { printf '%s' "$1" >"$SANDBOX/systemctl.fail"; }

# ^ invariant au_copy NAME [git] makes $SANDBOX/NAME a copy of what install needs; "git" adds a .git directory => install sees a checkout
# ^ why a copy, not the project tree; the tests hold whether or not the suite itself runs from a git checkout
au_copy() {
    local dir="$SANDBOX/$1" item
    rm -rf -- "$dir" && mkdir -p -- "$dir" || return 1
    for item in hooks lib bin tools.lock VERSION; do
        cp -R -- "$GSG_PROJECT/$item" "$dir/" || return 1
    done
    if [ "${2:-}" = git ]; then mkdir -- "$dir/.git" || return 1; fi
}

# ^ invariant a lifecycle sandbox with fixtures and one checkout copy at $AU_CO (its real path, as install records it)
au_begin() {
    lc_begin && lc_make_fixtures && lc_use_fixtures && au_copy co git || return 1
    AU_CO="$(realpath -- "$SANDBOX/co")"
}

gsg_from() {
    local dir="$1"
    shift
    run_cap env -i "${LC_ENV[@]}" "${EXTRA_ENV[@]}" "$SANDBOX/$dir/bin/git-secret-guard" "$@"
}

gsg_installed() { run_cap env -i "${LC_ENV[@]}" "${EXTRA_ENV[@]}" "$LC_DATA/bin/git-secret-guard" "$@"; }

# ^ invariant au_install [FLAG...] = au_begin plus one install from the checkout copy, asserted to succeed
au_install() {
    au_begin || return 1
    gsg_from co install "$@"
    assert_rc 0 "install $*"
}

# ^ security verify parses files in an in-process test manager; a scratch runtime dir keeps the real user manager's sockets out of reach
# ^ coupled the same call as verify_units of tests/autoupdate/test_timer.sh, here for the update units
verify_update_units() {
    mkdir -p -- "$SANDBOX/run" && chmod 700 "$SANDBOX/run" || return 1
    run_cap env -i HOME="$LC_HOME" PATH=/usr/bin:/bin XDG_RUNTIME_DIR="$SANDBOX/run" systemd-analyze --user verify "$(unit_dir)/$UPD_SERVICE" "$(unit_dir)/$UPD_TIMER"
}

assert_hook_events() {
    assert_eq "$(gitx config --global --get-all hook.git-secret-guard.event | tr '\n' ' ')" "pre-commit commit-msg " "$1"
}

assert_nothing_installed() {
    assert_no_file "$LC_STATE" "$1: no state dir"
    assert_no_file "$LC_DATA" "$1: no share dir"
    assert_no_file "$LC_BIN" "$1: no tools"
    assert_no_file "$(unit_dir)/$UPD_SERVICE" "$1: no update service"
    assert_empty "$(gitx config --global --get-regexp '^hook\.git-secret-guard\.')" "$1: no hook config"
}

# ^ invariant the holder may be gone already (a test dropped the lock itself) => a failed kill is not an error
au_drop_lock() {
    if [ -n "$AU_HOLDER" ]; then kill "$AU_HOLDER" 2>/dev/null || :; fi
    AU_HOLDER=""
    rm -f -- "$LC_STATE/update.lock"
}

# ^ coupled the lock is a symlink named after the holder's pid (doctor_rec_lock, generalised for update.lock); the holder is a live sleep
# ^ invariant each test runs in its own subshell (run_file_tests) => the EXIT trap ends the holder on every way out of the test
au_hold_lock() {
    sleep "$AU_HOLDER_SECONDS" &
    AU_HOLDER=$!
    trap au_drop_lock EXIT
    ln -s "$AU_HOLDER" "$LC_STATE/update.lock" || {
        au_drop_lock
        return 1
    }
}

# shellcheck disable=SC2016
AU_PRELUDE='set -u
GSG_ROOT="$1"
GSG_NAME=git-secret-guard
FAKE_UNAME="${FAKE_UNAME:-Linux}"
uname() { if [ "${1:-}" = -m ]; then echo x86_64; else echo "$FAKE_UNAME"; fi; }
for lib in platform/brew core/common core/state install/tools install/hookspath autoupdate/timer platform/launchd install/install autoupdate/install_timer install/install_tools platform/wsl gitup/gitup gitup/gitup_source integrations/desktop/desktop_git; do
    source "$1/lib/$lib.sh" || exit 9
done
shift
'

# ^ invariant au_lib CODE runs CODE over the real libraries with a uname function (FAKE_UNAME, default Linux), outside any lifecycle sandbox
au_lib() { run_cap env -i "${GSG_ENV[@]}" "${EXTRA_ENV[@]}" bash -c "$AU_PRELUDE$1" _ "$GSG_PROJECT"; }
