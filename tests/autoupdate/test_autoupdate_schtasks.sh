}

test_install_refuses_before_any_change_a_foreign_task_a_foreign_wrapper_and_a_long_action() {
    au_begin || return 1
    mkdir -p -- "$SANDBOX/schtasks.tasks" && printf '/Create /TN %s /SC DAILY /TR "C:\\other\\thing.cmd" /F\n' "$SCH_NAME" >"$SANDBOX/schtasks.tasks/$SCH_NAME" || return 1
    gsg_from co install --auto-update
    assert_rc 1 "a task of that name that is not ours"
    assert_contains "$ERR" "$SCH_NAME" "names the task"
    assert_contains "$ERR" "was not created by git-secret-guard" "says whose it is not"
    assert_nothing_installed "foreign task"
    assert_eq "$(sch_calls /Create)" 0 "nothing was created"
    rm -f -- "$SANDBOX/schtasks.tasks/$SCH_NAME" || return 1
    mkdir -p -- "$LC_STATE" && printf '@echo off\r\necho mine\r\n' >"$(sch_cmd)" || return 1
    gsg_from co install --auto-update
    assert_rc 1 "a wrapper file that is not ours"
    assert_contains "$ERR" "$(sch_cmd)" "names the file"
    assert_no_file "$LC_DATA" "no share dir"
    assert_eq "$(<"$(sch_cmd)")" $'@echo off\r\necho mine' "the foreign file is untouched"
    rm -rf -- "$LC_STATE"
    set_env XDG_STATE_HOME="$SANDBOX/xdg/state/$(printf 'x%.0s' {1..240})"
    gsg_from co install --auto-update
    assert_rc 1 "an action of more than 261 characters"
    assert_contains "$ERR" "261" "names the limit of /TR"
    assert_no_file "$LC_DATA" "refused before the share dir was made"
    assert_eq "$(sch_calls /Create)" 0 "nothing was created"
}

