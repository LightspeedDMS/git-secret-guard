test_the_update_plist_path_follows_the_shared_update_path() {
    local want_update='        <string>/usr/bin:/opt/homebrew/bin:/home/u/.local/bin:/opt/homebrew/opt/util-linux/bin:/opt/homebrew/opt/coreutils/libexec/gnubin:/usr/local/bin:/bin</string>'
    local want_doctor='        <string>/usr/bin:/usr/local/bin:/bin</string>'
    au_lib 'GSG_SHARE=/s GSG_AGENT_DIR=/a GSG_STATE_DIR=/st GSG_LAUNCHD_LABEL=d GSG_LAUNCHD_UPDATE_LABEL=u GSG_AGENT_PLIST=/a/d.plist GSG_AGENT_LOG=/st/d.log
        GSG_UPDATE_AGENT_PLIST=/a/u.plist GSG_UPDATE_AGENT_LOG=/st/u.log INSTALL_UPDATE_INTERVAL=1h INSTALL_BASH_BIN=/opt/homebrew/bin/bash
        INSTALL_JQ_BIN=/home/u/.local/bin/jq INSTALL_SETSID_BIN=/opt/homebrew/opt/util-linux/bin/setsid
        INSTALL_TIMEOUT_BIN=/opt/homebrew/opt/coreutils/libexec/gnubin/timeout
        unset XDG_DATA_HOME XDG_STATE_HOME XDG_CONFIG_HOME GIT_CONFIG_GLOBAL
        launchd_job_set update && launchd_plist_text /usr/bin | grep -A1 "<key>PATH</key>" | tail -n 1
        launchd_job_set doctor && launchd_plist_text /usr/bin | grep -A1 "<key>PATH</key>" | tail -n 1'
    assert_eq "$OUT" "$want_update"$'\n'"$want_doctor" "the update PATH holds the recorded tool directories once, the doctor PATH is as it was"
}

