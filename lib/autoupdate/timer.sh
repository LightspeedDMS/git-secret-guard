# shellcheck shell=bash disable=SC2153,SC2034

GSG_SERVICE_UNIT=git-secret-guard-doctor.service
GSG_TIMER_UNIT=git-secret-guard-doctor.timer
GSG_TIMER_MARKER='# generated by git-secret-guard install --with-timer; uninstall removes this file'
GSG_UPDATE_SERVICE_UNIT=git-secret-guard-update.service
GSG_UPDATE_TIMER_UNIT=git-secret-guard-update.timer
GSG_UPDATE_MARKER='# generated by git-secret-guard install --auto-update; uninstall removes this file'

# ^ invariant sets TU_* for one unit pair, $1 = doctor (--with-timer) or update (--auto-update); TU_SHORT and TU_LONG name the pair in messages
# ^ why a marker per pair, not one for both; each flag writes, refreshes and removes only the units it made
timer_unit_set() {
    case "$1" in
        doctor)
            TU_FLAG=--with-timer TU_SHORT=timer TU_LONG='weekly doctor timer'
            TU_MARKER="$GSG_TIMER_MARKER" TU_SERVICE="$GSG_SERVICE_UNIT" TU_TIMER="$GSG_TIMER_UNIT"
            ;;
        update)
            TU_FLAG=--auto-update TU_SHORT='auto-update timer' TU_LONG='auto-update timer'
            TU_MARKER="$GSG_UPDATE_MARKER" TU_SERVICE="$GSG_UPDATE_SERVICE_UNIT" TU_TIMER="$GSG_UPDATE_TIMER_UNIT"
            ;;
        *)
            printf '%s: internal error: unknown unit pair [%s]\n' "$GSG_NAME" "$1" >&2
            return 1
            ;;
    esac
}

# ^ why these four, not the whole environment; the user manager passes none on, a custom one at install time made the timer's doctor report not installed
# ^ invariant values set (non-empty) when install ran are written by timer_env_lines and checked by timer_check_target
GSG_TIMER_ENV_NAMES=(XDG_DATA_HOME XDG_STATE_HOME XDG_CONFIG_HOME GIT_CONFIG_GLOBAL)
# ^ why the update service carries the test interval, not the timer alone; update starts a child install, without it the child writes the timer back to 1h
# ^ invariant unset for users => the update units are what they are without the knob; install_update_interval refuses a value outside 1..999999
GSG_UPDATE_ENV_NAMES=(GSG_TEST_UPDATE_INTERVAL_SECONDS)

# ^ invariant the one definition of the update interval; users get 1h, the test knob of install gives <n>s with n in 1..999999
# ^ coupled the systemd timer unit, the launchd plist and the status and doctor report all read and write this grammar through timer_interval_seconds
GSG_UPDATE_INTERVAL=1h
GSG_UPDATE_INTERVAL_SECONDS=3600

# ^ invariant sets REPLY = the seconds of an update interval text, 1h or <n>s; rc 1 = any other text, never guessed
timer_interval_seconds() {
    if [ "$1" = "$GSG_UPDATE_INTERVAL" ]; then
        REPLY="$GSG_UPDATE_INTERVAL_SECONDS"
        return 0
    fi
    if [[ $1 =~ ^([1-9][0-9]{0,5})s$ ]]; then
        REPLY="${BASH_REMATCH[1]}"
        return 0
    fi
    return 1
}

# ^ invariant timer_env_lines [NAME...]; the names given are written after the four standing ones, each only when set
timer_env_lines() {
    local n
    for n in "${GSG_TIMER_ENV_NAMES[@]}" "$@"; do
        if [ -n "${!n:-}" ]; then printf 'Environment="%s=%s"\n' "$n" "${!n}"; fi
    done
}

# ^ invariant true only for a regular file (never a link) whose first line is the marker => install and uninstall touch only units they wrote
# ^ invariant $2 = the marker of the unit pair, the doctor pair's when absent
timer_unit_is_ours() {
    local first=""
    if [ ! -f "$1" ] || [ -L "$1" ]; then return 1; fi
    IFS= read -r first <"$1" || true
    [ "$first" = "${2:-$GSG_TIMER_MARKER}" ]
}

# ^ why only GIT_CONFIG_GLOBAL, not the XDG variables; paths_init already refuses a relative XDG_* before any command runs
# ^ invariant shared by the systemd units and the launchd plist; a relative value would point nowhere once the manager starts doctor elsewhere
timer_check_config_global() {
    local what
    if [ -n "${GIT_CONFIG_GLOBAL:-}" ] && [ "${GIT_CONFIG_GLOBAL#/}" = "$GIT_CONFIG_GLOBAL" ]; then
        what="${GIT_CONFIG_GLOBAL//[[:cntrl:]]/?}"
        trunc_text "$what" 120
        printf '%s: GIT_CONFIG_GLOBAL must be an absolute path to go into the timer unit (got [%s]); %s\n' "$GSG_NAME" "$REPLY" "$(brew_unchanged_text)" >&2
        return 1
    fi
}

# ^ why refuse these characters, not escape them; a quote, backslash, % or $ means something to systemd inside a path, and refusing is simpler to prove right
# ^ invariant $1 = the directory of the git install found first; every path written into a unit is checked, and a unit of ours is the only one replaced
# ^ invariant timer_check_values GITDIR [NAME...]; the names given are the extra variables of one unit pair, checked like the standing ones
timer_check_values() {
    local what n
    local -a values=("$GSG_SHARE" "$GSG_UNIT_DIR" "$1")
    timer_check_config_global || return 1
    for n in "${GSG_TIMER_ENV_NAMES[@]}" "${@:2}"; do
        if [ -n "${!n:-}" ]; then values+=("${!n}"); fi
    done
    for what in "${values[@]}"; do
        case "$what" in
            *'"'* | *\\* | *'%'* | *'$'*) ;;
            *[[:cntrl:]]*) ;;
            *) continue ;;
        esac
        printf '%s: %s cannot be written into a systemd unit (it holds a quote, a backslash, %% or $, or a control character); %s\n' "$GSG_NAME" "${what//[[:cntrl:]]/?}" "$(brew_unchanged_text)" >&2
        return 1
    done
}

# ^ invariant timer_check_target GITDIR [MARKER UNIT...]; without a list it checks the two doctor units against the doctor marker
timer_check_target() {
    local marker="${2:-$GSG_TIMER_MARKER}" unit path
    local -a units=("${@:3}") names=()
    if [ "${#units[@]}" -eq 0 ]; then units=("$GSG_SERVICE_UNIT" "$GSG_TIMER_UNIT"); fi
    if [ "$marker" = "$GSG_UPDATE_MARKER" ]; then names=("${GSG_UPDATE_ENV_NAMES[@]}" "${GSG_UPDATE_PATH_NAMES[@]}"); fi
    timer_check_values "$1" "${names[@]}" || return 1
    for unit in "${units[@]}"; do
        path="$GSG_UNIT_DIR/$unit"
        if { [ -e "$path" ] || [ -L "$path" ]; } && ! timer_unit_is_ours "$path" "$marker"; then
            printf '%s: %s exists and was not written by git-secret-guard; move it away and run install again; %s\n' "$GSG_NAME" "$path" "$(brew_unchanged_text)" >&2
            return 1
        fi
    done
}

# ^ invariant prints the git dir ($1) first, followed by /usr/local/bin:/usr/bin:/bin, each directory once, in order
timer_unit_path() {
    local d out=""
    for d in "$1" /usr/local/bin /usr/bin /bin; do
        case ":$out:" in
            *":$d:"*) ;;
            *) out+="${out:+:}$d" ;;
        esac
    done
    printf '%s' "$out"
}

# ^ invariant the tools the child install of an update run looks up on PATH (install/install.sh:install_resolve_bins); install-time values, never a new lookup
GSG_UPDATE_PATH_NAMES=(INSTALL_BASH_BIN INSTALL_JQ_BIN INSTALL_SETSID_BIN INSTALL_TIMEOUT_BIN)

# ^ invariant sets REPLY = the PATH of the update job, the git dir first, the directory of each recorded tool once, the fixed directories last
# ^ why a tool directory inside the fixed ones is skipped, not listed again; with the tools in /usr/bin the PATH stays what the units always had
timer_update_path() {
    local n d extra=""
    for n in "${GSG_UPDATE_PATH_NAMES[@]}"; do
        d="${!n:-}"
        d="${d%/*}"
        if [ -z "$d" ]; then continue; fi
        case ":$1:$extra:/usr/local/bin:/usr/bin:/bin:" in
            *":$d:"*) continue ;;
        esac
        extra+=":$d"
    done
    REPLY="$(timer_unit_path "$1")"
    REPLY="$1$extra${REPLY#"$1"}"
}

# ^ external a quoted ExecStart path and Environment="NAME=value" are valid unit syntax; systemd-analyze --user verify in tests/autoupdate/test_timer.sh
# ^ external the user manager has its own PATH; the unit carries the PATH of the git install found first, the same git doctor needs
# ^ invariant timer_unit_service_text MARKER DESCRIPTION PATH ARGS [NAME...]; ARGS = the CLI arguments after the program path, NAME... go to timer_env_lines
timer_unit_service_text() {
    printf '%s\n' "$1" '[Unit]' "Description=$2" '' '[Service]' 'Type=oneshot' 'TimeoutStartSec=1h' \
        "Environment=\"PATH=$3\""
    timer_env_lines "${@:5}"
    printf '%s\n' "ExecStart=\"$GSG_SHARE/bin/git-secret-guard\" $4"
}

# ^ invariant timer_unit_timer_text MARKER DESCRIPTION SERVICE_UNIT SCHEDULE_LINE...; the schedule lines open the [Timer] section
timer_unit_timer_text() {
    printf '%s\n' "$1" '[Unit]' "Description=$2" '' '[Timer]' "${@:4}" "Unit=$3" '' '[Install]' 'WantedBy=timers.target'
}

GSG_TIMER_DESCRIPTION='git-secret-guard weekly coverage report (doctor)'

timer_service_text() { timer_unit_service_text "$GSG_TIMER_MARKER" "$GSG_TIMER_DESCRIPTION" "$(timer_unit_path "$1")" doctor; }

timer_timer_text() { timer_unit_timer_text "$GSG_TIMER_MARKER" "$GSG_TIMER_DESCRIPTION" "$GSG_SERVICE_UNIT" 'OnCalendar=weekly' 'Persistent=true'; }

# ^ invariant a unit appears complete or not at all => temp file beside it, rename after the write
timer_write_unit() {
    local path="$1" tmp
    tmp="$(mktemp "${path%/*}/.gsg-unit.XXXXXX")" || return 1
    if ! printf '%s\n' "$2" >"$tmp" || ! chmod 644 -- "$tmp" || ! mv -f -- "$tmp" "$path"; then
        rm -f -- "$tmp"
        return 1
    fi
}

GSG_UPDATE_DESCRIPTION='git-secret-guard auto-update'

# ^ invariant the update service runs exactly "<share>/bin/git-secret-guard" update, PATH = timer_update_path of the git dir ($1) and the recorded tool dirs
timer_update_service_text() {
    timer_update_path "$1" || return 1
    timer_unit_service_text "$GSG_UPDATE_MARKER" "$GSG_UPDATE_DESCRIPTION" "$REPLY" update "${GSG_UPDATE_ENV_NAMES[@]}"
}

# ^ invariant $1 = the time between two runs as systemd writes it (1h; <n>s under the test knob of install); the first run comes 5 minutes after boot
timer_update_timer_text() {
    timer_unit_timer_text "$GSG_UPDATE_MARKER" "$GSG_UPDATE_DESCRIPTION" "$GSG_UPDATE_SERVICE_UNIT" 'OnBootSec=5min' "OnUnitActiveSec=$1"
}

# ^ invariant timer_write_units SERVICE_UNIT SERVICE_TEXT TIMER_UNIT TIMER_TEXT; the service is written first => a timer never names a missing service
timer_write_units() {
    mkdir -p -- "$GSG_UNIT_DIR" || return 1
    timer_write_unit "$GSG_UNIT_DIR/$1" "$2" || return 1
    timer_write_unit "$GSG_UNIT_DIR/$3" "$4"
}
