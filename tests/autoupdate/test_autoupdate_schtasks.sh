    assert_contains "$OUT" "interval unknown, $(sch_cmd) is missing or not ours" "status cannot read the interval of a wrapper that is not ours"
    gsg_installed doctor --roots "$SANDBOX/roots"
    assert_rc 1 "doctor with a foreign wrapper"
    assert_contains "$OUT" "auto-update: timer inactive: $(sch_cmd) was not written by git-secret-guard" "the PROBLEM names the file"
    assert_contains "$OUT" "move it away and run: $AU_CO/bin/git-secret-guard install --auto-update" "and the whole fix"
    assert_eq "$(sch_log)" "" "status and doctor never run schtasks"
}

# ^ invariant a wrapper of an earlier install (marker on line 2, no setlocal) is ours, and a plain install writes it again with the line
test_a_plain_install_rewrites_an_older_wrapper_that_lacks_the_setlocal_line() {
    sch_install
    assert_rc 0 "install --auto-update"
    sed -i '3d' "$(sch_cmd)" || return 1
    assert_not_contains "$(<"$(sch_cmd)")" "setlocal" "the wrapper is now the older shape"
    : >"$SANDBOX/schtasks.log"
    gsg_from co install
    assert_rc 0 "a plain install"
    assert_eq "$(sed -n 3p "$(sch_cmd)" | tr -d '\r')" "setlocal DisableDelayedExpansion" "the line is back"
    assert_eq "$(sed -n 2p "$(sch_cmd)" | tr -d '\r')" "$SCH_MARKER" "the marker is still line 2"
    assert_eq "$(sch_log)" "" "and schtasks was not called"
}

