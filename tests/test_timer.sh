#!/usr/bin/env bash
# shellcheck source=tests/lib.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/lib.sh"
# shellcheck source=tests/lifecycle.sh
source "$(dirname -- "${BASH_SOURCE[0]}")/lifecycle.sh"

# ^ external Windows has no systemd => install --with-timer is refused there; test_prerequisites.sh covers the refusal
if [ "$TEST_IS_WINDOWS" -eq 1 ]; then FILE_SKIP_REASON="systemd timer, Windows has no systemd"; fi

SERVICE=git-secret-guard-doctor.service
TIMER=git-secret-guard-doctor.timer
MARKER_LINE="# generated by git-secret-guard install --with-timer; uninstall removes this file"

unit_dir() { printf '%s' "$LC_HOME/.config/systemd/user"; }
systemctl_log() { if [ -f "$SANDBOX/systemctl.log" ]; then cat -- "$SANDBOX/systemctl.log"; fi; }

timer_begin() {
    lc_begin && lc_make_fixtures && lc_use_fixtures
}

# ^ security verify parses files in an in-process test manager; a scratch runtime dir keeps the real user manager's sockets out of reach
verify_units() {
    mkdir -p -- "$SANDBOX/run" && chmod 700 "$SANDBOX/run" || return 1
    run_cap env -i HOME="$LC_HOME" PATH=/usr/bin:/bin XDG_RUNTIME_DIR="$SANDBOX/run" systemd-analyze --user verify "$(unit_dir)/$SERVICE" "$(unit_dir)/$TIMER"
}

test_the_lifecycle_tests_can_only_reach_the_systemctl_stand_in() {
    lc_begin || return 1
    # shellcheck disable=SC2016
    assert_eq "$(env -i "${LC_ENV[@]}" bash -c 'type -P systemctl')" "$SANDBOX/pathbin/systemctl" "the stand-in is first on the lifecycle PATH"
    lc_path_without jq || return 1
    # shellcheck disable=SC2016
    assert_eq "$(readlink -- "$SANDBOX/pathfarm-jq/systemctl")" "$SANDBOX/pathbin/systemctl" "and the PATH farm links it instead of /usr/bin/systemctl"
}

test_install_with_timer_writes_the_units_and_enables_the_timer_through_the_recorded_systemctl() {
    timer_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer"
    assert_eq "$(systemctl_log)" "--user enable --now $TIMER" "exactly one systemctl call, the one the story names"
    assert_eq "$(sed -n 1p "$(unit_dir)/$SERVICE")" "$MARKER_LINE" "the service carries the marker"
    assert_contains "$(<"$(unit_dir)/$SERVICE")" 'Type=oneshot' "a one-shot service"
    assert_contains "$(<"$(unit_dir)/$SERVICE")" "ExecStart=\"$LC_DATA/bin/git-secret-guard\" doctor" "it runs doctor from the installed copy"
    assert_contains "$(<"$(unit_dir)/$SERVICE")" 'Environment="PATH='"$(lc_first_git_dir)"':' "with the PATH of the git that install found first"
    assert_eq "$(sed -n 1p "$(unit_dir)/$TIMER")" "$MARKER_LINE" "the timer carries the marker"
    assert_contains "$(<"$(unit_dir)/$TIMER")" 'OnCalendar=weekly' "weekly"
    assert_contains "$(<"$(unit_dir)/$TIMER")" 'Persistent=true' "a missed run is caught up"
    assert_contains "$(<"$(unit_dir)/$TIMER")" 'WantedBy=timers.target' "installable"
    assert_eq "$(state_value timer_installed)" yes "the state records the timer"
    assert_contains "$(<"$LC_DATA/settings")" "SYSTEMCTL_BIN=$SANDBOX/pathbin/systemctl" "the settings record the systemctl path found at install time"
    assert_contains "$OUT" "weekly doctor timer enabled" "the summary says so"
    assert_contains "$OUT" "journalctl --user -u $SERVICE" "and how to read the output"
}

