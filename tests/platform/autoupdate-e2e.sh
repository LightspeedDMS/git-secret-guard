DEAD_PROXY=(HTTPS_PROXY=http://127.0.0.1:9 HTTP_PROXY=http://127.0.0.1:9 https_proxy=http://127.0.0.1:9 http_proxy=http://127.0.0.1:9)

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)" || exit 2
# shellcheck source=tests/platform/autoupdate-e2e-lib.sh
source "$HERE/autoupdate-e2e-lib.sh" || exit 2
# shellcheck source=tests/platform/autoupdate-e2e-visibility.sh
source "$HERE/autoupdate-e2e-visibility.sh" || exit 2
# ^ invariant 1 runs the #130 group (status and doctor) between steps 7 and 8; 0 leaves exactly the steps of #129
VISIBILITY_STEPS=1

# ^ invariant og = git as the owner in the checkout the installs follow, dg = git as the owner in the second clone releases are pushed from
# ^ security no git command runs as root on the checkout => no safe.directory entry exists anywhere in the container
og() { as "$OWNER" git -C "$CHECKOUT" "$@"; }
dg() { as "$OWNER" git -C "$DEV" "$@"; }

setup_users_and_git() {
    local account
    groupadd --force "$GROUP" || return 1
    for account in "$OWNER" "$FOLLOWER" "$NOBUS"; do
        useradd -m -s /bin/bash -g "$GROUP" "$account" || return 1
    done
    mkdir -p "$CHECKOUT" || return 1
    cp -a /src/. "$CHECKOUT/" || return 1
    chown -R "$OWNER:$GROUP" "$CHECKOUT" || return 1
    chmod -R g+rwX "$CHECKOUT" || return 1
    bare "$OWNER" git config --global user.name 'GSG Owner' || return 1
    bare "$OWNER" git config --global user.email owner@example.invalid || return 1
    og init -q -b main || return 1
    og add . || return 1
    og commit -q -m initial || return 1
    og tag "v$BASE" || return 1
    bare "$OWNER" git init -q --bare --initial-branch=main "$ORIGIN" || return 1
    og remote add origin "file://$ORIGIN" || return 1
    og push -q origin main "v$BASE" || return 1
    bare "$OWNER" git clone -q "file://$ORIGIN" "$DEV" || return 1
    chmod 775 "$CHECKOUT" "$CHECKOUT/.git"
}

enable_linger_and_wait() {
    local account n up
    for account in "$OWNER" "$FOLLOWER"; do
        loginctl enable-linger "$account" || return 1
        up=0
        for ((n = 0; n < MANAGER_WAIT && up == 0; n++)); do
            if as "$account" systemctl --user is-system-running >/dev/null 2>&1; then up=1; else sleep 1; fi
        done
        if [ "$up" -ne 1 ]; then return 1; fi
    done
}

user_timer_fires() {
    local n fired="/home/$FOLLOWER/.gsg-autoupdate-timer-fired" unit="gsg-e2e-tick-$$"
    rm -f "$fired" || return 1
    # ^ external a timer's default AccuracySec is 1min; a 3s timer once fired 31 s late (observed) => this one asks for 1s
    as "$FOLLOWER" systemd-run --user --unit="$unit" --on-active="${TICK_SECONDS}s" --timer-property=AccuracySec=1s /usr/bin/touch "$fired" || return 1
    for ((n = 0; n < MANAGER_WAIT; n++)); do
        if [ -e "$fired" ]; then return 0; fi
        sleep 1
    done
    as "$FOLLOWER" systemctl --user status "$unit.timer" "$unit.service" >&2 || :
    return 1
}

prepare_container() {
    [ "${GSG_PLATFORM_SENTINEL:-}" = host-environment-must-not-arrive ] || return 1
    [ -r /src/VERSION ] && [ ! -w /src ] || return 1
    [ "$(ps -p 1 -o comm= | tr -d ' ')" = systemd ] || return 1
    # ^ invariant distinct systemd-mode mount allowlist is based on this launcher's measured mount set, not ubuntu --init
    # ^ external observed rootless podman 5.6 systemd-mode mounts; not the ubuntu --init set
    local -A allowed=([/]=1 [/proc]=1 [/proc/acpi]=1 [/proc/scsi]=1 [/proc/kcore]=1 [/proc/keys]=1 [/proc/latency_stats]=1 [/proc/timer_list]=1 [/proc/interrupts]=1 [/proc/asound]=1 [/proc/bus]=1 [/proc/fs]=1 [/proc/irq]=1 [/proc/sys]=1 [/proc/sysrq-trigger]=1 [/dev]=1 [/dev/pts]=1 [/dev/shm]=1 [/dev/mqueue]=1 [/dev/null]=1 [/dev/zero]=1 [/dev/full]=1 [/dev/tty]=1 [/dev/random]=1 [/dev/urandom]=1 [/sys]=1 [/sys/fs/cgroup]=1 [/sys/devices/virtual/powercap]=1 [/sys/firmware]=1 [/sys/fs/selinux]=1 [/run]=1 [/run/lock]=1 [/run/.containerenv]=1 [/tmp]=1 [/etc/hosts]=1 [/etc/hostname]=1 [/etc/resolv.conf]=1 [/src]=1)
    local point unexpected=""
    while read -r point; do
        case "$point" in /proc/*|/dev/*|/sys/*|/run/*|/etc/*) ;; *) continue ;; esac
        # ^ external podman masks one thermal_throttle directory per CPU of the host; the family is matched, never a core count
        if [[ $point =~ ^/sys/devices/system/cpu/cpu[0-9]+/thermal_throttle$ ]]; then continue; fi
        [ -n "${allowed[$point]+yes}" ] || unexpected+=" $point"
    done < <(awk '{print $5}' /proc/self/mountinfo)
    if [ -n "$unexpected" ]; then printf 'observed extra systemd-mode mount points:%s\n' "$unexpected" >&2; return 1; fi
}

# ^ security the fake key is built from fragments at run time and never printed; see tests/support/lib.sh:fake_aws_key, the same value
fake_key() { printf '%s%s' "AKI""A" "Q7XK2MWB4HZ5NR3T"; }

# ^ invariant bump N prints BASE (x.y.z, checked by the main block) with its patch number raised by N
bump() {
    local -a parts=()
    IFS=. read -r -a parts <<<"$BASE" || return 1
    printf '%s.%s.%s' "${parts[0]}" "${parts[1]}" "$((10#${parts[2]} + $1))"
}

# ^ invariant release VERSION KIND pushes to the origin from the owner's second clone; the tagged kinds bump VERSION in the tagged commit
# ^ invariant broken = the installer of the tagged tree refuses, untagged = a commit on main and no tag, any other kind = a sound release
release() {
    local v="$1" kind="$2"
    case "$kind" in
        untagged) printf '\nuntagged e2e commit\n' >>"$DEV/README.md" || return 1 ;;
        broken)
            printf '%s\n' '#!/usr/bin/env bash' "printf 'git-secret-guard: this release refuses to install\\n' >&2" 'exit 1' >"$DEV/bin/git-secret-guard" || return 1
            printf '%s\n' "$v" >"$DEV/VERSION" || return 1
            ;;
        *)
            dg checkout -q "v$BASE" -- bin/git-secret-guard || return 1
            printf '%s\n' "$v" >"$DEV/VERSION" || return 1
            ;;
    esac
    dg commit -q -a -m "e2e $kind $v" || return 1
    if [ "$kind" = untagged ]; then
        dg push -q origin main
        return
    fi
    dg tag -a -m "v$v" "v$v" || return 1
    dg push -q origin main "v$v"
}

# ^ invariant expect_at_tag VERSION LABEL, the checkout's HEAD is exactly the commit of tag vVERSION; two failed lookups never pass (check_eq)
expect_at_tag() { check_eq "$(og rev-parse HEAD)" "$(og rev-parse "refs/tags/v$1^{commit}")" "$2"; }

# ^ invariant expect_installed ACCOUNT VERSION, both the installed copy and the state file name VERSION
expect_installed() {
    local share state
    share="$(path_of "$1" share)" && state="$(path_of "$1" state)" || return 1
    check_eq "$(head -n 1 "$share/VERSION")|$(grep '^version=' "$state/state")" "$2|version=$2" "$1: the installed VERSION and the state's version are $2"
}

# ^ invariant expect_update ACCOUNT ROLE FROM TO awaits a record of exactly this role, updated, no reason, no detail, from and to
expect_update() {
    expect_run "$1" 0 "\\|role=$2\\|result=updated\\|reason=\\|detail=\\|from=${3//./\\.}\\|to=${4//./\\.}\$" "$1: a timer run records $2, updated, $3 -> $4"
    expect_installed "$1" "$4"
}

install_checks() {
    local a="$1" units share state
    if ! units="$(path_of "$a" units)" || ! share="$(path_of "$a" share)" || ! state="$(path_of "$a" state)"; then
        report bad "$a: the install paths cannot be named"
        return 1
    fi
    run "install-$a" as "$a" GSG_TEST_UPDATE_INTERVAL_SECONDS="$INTERVAL" "$CHECKOUT/bin/git-secret-guard" install --auto-update
    check_rc 0 "$a: install --auto-update from the owner's checkout"
    check_has "$ERRF" "TEST OVERRIDE active (GSG_TEST_UPDATE_INTERVAL_SECONDS=[$INTERVAL]); the update timer runs every $INTERVAL seconds, not hourly" "$a: the interval override is announced on stderr"
    check_has "$OUTF" "auto-update now follows $CHECKOUT" "$a: install names the checkout it follows"
    check_has "$OUTF" "loginctl enable-linger" "$a: the linger hint is printed"
    check_eq "$(head -n 1 "$units/$SERVICE")|$(head -n 1 "$units/$TIMER")" "$MARKER|$MARKER" "$a: both update units start with the --auto-update marker"
    check_has "$units/$SERVICE" "ExecStart=\"$share/bin/git-secret-guard\" update" "$a: ExecStart is the installed CLI with update"
    check_has "$units/$SERVICE" "Environment=\"GSG_TEST_UPDATE_INTERVAL_SECONDS=$INTERVAL\"" "$a: the service file carries the interval knob"
    check_has "$units/$TIMER" "OnUnitActiveSec=${INTERVAL}s" "$a: the timer has OnUnitActiveSec=${INTERVAL}s"
    check_has "$units/$TIMER" "OnBootSec=5min" "$a: the timer has OnBootSec=5min"
    run "enabled-$a" as "$a" systemctl --user is-enabled "$TIMER"
    check_eq "$RC|$(<"$OUTF")" "0|enabled" "$a: systemd says the timer is enabled"
    run "active-$a" as "$a" systemctl --user is-active "$TIMER"
    check_eq "$RC|$(<"$OUTF")" "0|active" "$a: systemd says the timer is active"
    run "env-$a" as "$a" systemctl --user show --property=Environment "$SERVICE"
    check_has "$OUTF" "GSG_TEST_UPDATE_INTERVAL_SECONDS=$INTERVAL" "$a: the loaded service environment carries the knob"
    check_has "$state/state" "auto_update=yes" "$a: the state records auto_update=yes"
    check_has "$state/state" "source_checkout=$CHECKOUT" "$a: the state records the checkout"
    check_ok "$a: no doctor timer unit was written" gone "$units/git-secret-guard-doctor.timer" "$units/git-secret-guard-doctor.service"
}

step_install() {
    printf '== step 3: both users install --auto-update with GSG_TEST_UPDATE_INTERVAL_SECONDS=%s\n' "$INTERVAL"
    install_checks "$OWNER"
    install_checks "$FOLLOWER"
    # ^ coupled wait_run reads RUN_BOUND; this local gives the two waits below the bound of the timer's first run, and only them
    local RUN_BOUND="$FIRST_RUN_BOUND"
    expect_run "$OWNER" 0 '\|role=owner\|result=current\|' "$OWNER: the timer's first run (OnBootSec) records current"
    expect_run "$FOLLOWER" 0 '\|role=follower\|result=current\|' "$FOLLOWER: the timer's first run (OnBootSec) records current"
}

step_probe() {
    printf '== step 4: the safe.directory probe as %s against the checkout of %s\n' "$FOLLOWER" "$OWNER"
    run probe-plain bare "$FOLLOWER" git -C "$CHECKOUT" rev-parse HEAD
    check_rc 128 "without safe.directory git refuses the other user's checkout"
    check_has "$ERRF" "dubious ownership" "and names the dubious ownership"
    run probe-safe bare "$FOLLOWER" git -c "safe.directory=$CHECKOUT" -C "$CHECKOUT" rev-parse HEAD
    check_rc 0 "with -c safe.directory=<the exact checkout> the same command succeeds"
    check_eq "$(<"$OUTF")" "$(og rev-parse HEAD)" "and prints the owner's HEAD"
}

step_release() {
    local v="$1" a
    printf '== step 5: tag v%s is pushed to the origin, both records are polled\n' "$v"
    fixture marker as "$OWNER" touch "$CHECKOUT/lib/e2e-untracked-marker" || return 1
    mark || return 1
    fixture "release-$v" release "$v" good || return 1
    expect_update "$OWNER" owner "$BASE" "$v"
    expect_update "$FOLLOWER" follower "$BASE" "$v"
    expect_at_tag "$v" "the owner's checkout HEAD is exactly v$v^{commit}"
    check_eq "$(og rev-list --count --min-parents=2 "v$BASE..HEAD")" 0 "the fast-forward made no merge commit"
    for a in "$OWNER" "$FOLLOWER"; do
        check_ok "$a: the untracked work tree file is not in the installed copy (the install came from the tag export)" \
            gone "$(path_of "$a" share)/lib/e2e-untracked-marker"
        check_has "$(path_of "$a" units)/$TIMER" "OnUnitActiveSec=${INTERVAL}s" "$a: the child install kept the ${INTERVAL}s timer"
    done
}

step_untagged() {
    printf '== step 6a: an untagged push\n'
    snap_take
    mark || return 1
    fixture release-untagged release "" untagged || return 1
    # ^ why skip 1, not 0; a run started before the push may still write current, the record after it was made past the push
    expect_run "$OWNER" 1 '\|role=owner\|result=current\|' "$OWNER: only untagged commits on origin/main, the record says current"
    expect_run "$FOLLOWER" 1 '\|role=follower\|result=current\|' "$FOLLOWER: the record says current"
    check_eq "$(og rev-parse refs/remotes/origin/main)" "$(dg rev-parse HEAD)" "untagged: the fetch did bring the commit to origin/main"
    expect_at_tag "$1" "untagged: the checkout stays at v$1, the commit is not merged"
    expect_unchanged untagged
}

# ^ invariant skip_case REASON HEAD awaits the owner's record of the skip REASON; the obstacle is in place and a newer tag waits on the origin
skip_case() {
    mark || return 1
    expect_run "$OWNER" 0 "\\|role=owner\\|result=skipped\\|reason=$1\\|" "$1: the owner's record names the skip"
    check_eq "$(og rev-parse HEAD)" "$2" "$1: the checkout HEAD did not move"
    expect_unchanged "$1"
}

# ^ order each obstacle is put in place before the one before it is removed => no timer run ever sees a checkout free to update
# ^ invariant step_skips VERSION PREVIOUS; tag vVERSION waits on the origin through all of them, the control at the end installs it
step_skips() {
    local v="$1" head
    printf '== step 6b: v%s waits on the origin behind a dirty tree, another branch, no origin, a shallow repository\n' "$v"
    snap_take
    if ! head="$(og rev-parse HEAD)"; then
        report bad "step 6b: the checkout's HEAD cannot be read"
        return 1
    fi
    fixture dirty cp /src/VERSION "$CHECKOUT/README.md" || return 1
    fixture "release-$v" release "$v" good || return 1
    skip_case dirty "$head"
    fixture side-branch og checkout -q -b e2e-side || return 1
    fixture clean og checkout -q -- README.md || return 1
    skip_case not-on-main "$head"
    fixture side-commit og commit -q --allow-empty --no-verify -m 'e2e side commit' || return 1
    mark || return 1
    expect_run "$FOLLOWER" 0 '\|role=follower\|result=skipped\|reason=not-at-tag\|' "not-at-tag: the follower skips a HEAD that is no release"
    expect_unchanged not-at-tag
    fixture no-origin og remote remove origin || return 1
    fixture main og checkout -q main || return 1
    fixture side-gone og branch -q -D e2e-side || return 1
    skip_case no-origin "$head"
    fixture shallow og fetch -q --depth=1 "file://$ORIGIN" main || return 1
    fixture origin-back og remote add origin "file://$ORIGIN" || return 1
    check_eq "$(og rev-parse --is-shallow-repository)" true "shallow: git says the checkout is shallow"
    skip_case shallow "$head"
    printf '== step 6b control: the obstacles are gone, v%s installs\n' "$v"
    mark || return 1
    fixture unshallow og fetch -q --unshallow "file://$ORIGIN" main || return 1
    expect_update "$OWNER" owner "$2" "$v"
    expect_update "$FOLLOWER" follower "$2" "$v"
    expect_at_tag "$v" "control: the checkout is at v$v"
}

# ^ invariant hand_update ACCOUNT runs the installed CLI's update as the account; RC, OUTF and ERRF are those of the run the lock let in
hand_update() {
    local cli
    cli="$(path_of "$1" cli)" || return 1
    retry_locked "hand-$1" out 'skipped (locked)' as "$1" "$cli" update
}

blocked_commit() {
    local a="$1" repo="/home/$1/e2e-leak"
    fixture "leak-repo-$a" as "$a" git init -q -b main "$repo" || return 1
    if ! printf 'one\naws_access_key_id = %s\n' "$(fake_key)" >"$repo/leak.txt" || ! chown "$a:$GROUP" "$repo/leak.txt"; then
        report bad "fixture leak file of $a"
        return 1
    fi
    fixture "leak-add-$a" as "$a" git -C "$repo" add leak.txt || return 1
    run "leak-$a" as "$a" "${DEAD_PROXY[@]}" git -C "$repo" -c user.name=E2E -c user.email=e2e@example.invalid commit -q -m leak
    check_rc 1 "$a: after the failed update a commit with a fake AWS key is still blocked"
    check_has "$ERRF" "leak.txt:2" "$a: the old hook names the file and line"
    run "leak-head-$a" as "$a" git -C "$repo" rev-parse -q --verify HEAD
    check_rc 1 "$a: no commit was created"
}

# ^ invariant step_broken BROKEN PREVIOUS NEXT; vBROKEN is a release whose installer refuses, vNEXT a sound one pushed after it
step_broken() {
    local v="$1" a failed='\|result=failed\|reason=install-failed\|detail=[^|]*this release refuses to install'
    printf '== step 6c: v%s is a tag whose install refuses\n' "$v"
    snap_take
    mark || return 1
    fixture "release-$v" release "$v" broken || return 1
    expect_run "$OWNER" 0 "\\|role=owner$failed" "$OWNER: the record says failed, install-failed"
    expect_run "$FOLLOWER" 0 "\\|role=follower$failed" "$FOLLOWER: the record says failed, install-failed"
    # ^ order the mark is taken again after the first failed record => only a later run's record can prove the retry
    mark || return 1
    expect_run "$OWNER" 0 "\\|role=owner$failed" "$OWNER: the next timer run retries and fails the same way"
    expect_at_tag "$v" "broken tag: the checkout was fast-forwarded to v$v"
    expect_unchanged "broken tag"
    for a in "$OWNER" "$FOLLOWER"; do
        hand_update "$a"
        check_rc 1 "$a: update by hand exits 1 for the failed install"
        check_has "$ERRF" "update: failed (install-failed): git-secret-guard: this release refuses to install" "$a: and says why on stderr"
        blocked_commit "$a"
    done
    printf '== step 6c control: v%s is a sound release after the broken one\n' "$3"
    mark || return 1
    fixture "release-$3" release "$3" good || return 1
    expect_update "$OWNER" owner "$2" "$3"
    expect_update "$FOLLOWER" follower "$2" "$3"
    expect_at_tag "$3" "control: the checkout is at v$3"
}

step_by_hand() {
    local v="$1" a role timer hand
    printf '== step 7: update by hand as each user, compared with the timer\n'
    for a in "$OWNER" "$FOLLOWER"; do
        role=follower
        if [ "$a" = "$OWNER" ]; then role=owner; fi
        mark || return 1
        expect_run "$a" 0 "\\|role=$role\\|result=current\\|" "$a: the timer's run after the update says current"
        timer="${REPLY#*|}"
        hand_update "$a"
        check_rc 0 "$a: update by hand exits 0"
        check_eq "$(<"$OUTF")" "git-secret-guard: update: current, $v is installed" "$a: and prints the one line"
        if ! hand="$(record_line "$a")"; then hand=""; fi
        check_eq "${hand#*|}" "$timer" "$a: the record after the hand run equals the timer's (all but checked_at)"
    done
    run safe-config bare "$FOLLOWER" git config --global --get-all safe.directory
    check_rc 1 "$FOLLOWER: no safe.directory was ever written to the follower's git config"
}

# ^ invariant home_listing ACCOUNT prints every path under the account's home with type, size and mode, sorted; a failing find or sort is its status
home_listing() { find "/home/$1" -printf '%P %y %s %m\n' | sort; }

step_unreachable() {
    local before after refusal='--auto-update needs your systemd user manager, and it cannot be reached'
    printf '== step 8: install --auto-update where the systemd user manager cannot be reached\n'
    if ! before="$(home_listing "$NOBUS")"; then
        report bad "step 8: the home of $NOBUS cannot be listed"
        return 1
    fi
    run nobus as "$NOBUS" "$CHECKOUT/bin/git-secret-guard" install --auto-update
    check_rc 1 "$NOBUS (no session, no linger): install --auto-update is refused"
    check_has "$ERRF" "$refusal" "$NOBUS: the refusal names the unreachable manager"
    check_has "$ERRF" "nothing was changed" "$NOBUS: and says nothing was changed"
    if ! after="$(home_listing "$NOBUS")"; then after="$(unreadable)"; fi
    check_eq "$after" "$before" "$NOBUS: no file of the home directory was made or changed"
    check_ok "$NOBUS: no installed copy, state dir, unit or CLI link exists" gone "$(path_of "$NOBUS" share)" "$(path_of "$NOBUS" state)" \
        "$(path_of "$NOBUS" units)/$SERVICE" "$(path_of "$NOBUS" units)/$TIMER" "$(path_of "$NOBUS" cli)"
    snap_take
    run nobus-existing bare "$FOLLOWER" "$CHECKOUT/bin/git-secret-guard" install --auto-update
    check_rc 1 "$FOLLOWER without XDG_RUNTIME_DIR: install --auto-update is refused over the existing install"
    check_has "$ERRF" "$refusal" "$FOLLOWER: the refusal names the unreachable manager"
    expect_unchanged "refused install"
}

uninstall_checks() {
    local a="$1" units state share cli
    if ! units="$(path_of "$a" units)" || ! state="$(path_of "$a" state)" || ! share="$(path_of "$a" share)" || ! cli="$(path_of "$a" cli)"; then
        report bad "$a: the install paths cannot be named"
        return 1
    fi
    retry_locked "uninstall-$a" err 'did not get the update lock' as "$a" "$cli" uninstall
    check_rc 0 "$a: uninstall"
    check_ok "$a: both update units and the timers.target.wants link are gone" gone "$units/$SERVICE" "$units/$TIMER" "$units/timers.target.wants/$TIMER"
    check_ok "$a: the update lock and the update record are gone" gone "$state/update.lock" "$state/update"
    check_ok "$a: the state dir is removed" gone "$state"
    check_ok "$a: the installed copy and the CLI link are gone" gone "$share" "$cli"
    run "inactive-$a" as "$a" systemctl --user is-active "$TIMER"
    check_eq "$(<"$OUTF")" inactive "$a: systemd no longer has the timer active"
    run "hookcfg-$a" as "$a" git config --global --get-regexp '^hook\.git-secret-guard\.'
    check_rc 1 "$a: the hook config is gone"
}

step_uninstall() {
    printf '== step 9: uninstall as each user\n'
    uninstall_checks "$FOLLOWER"
    uninstall_checks "$OWNER"
    sleep "$((INTERVAL + UNINSTALL_GRACE))"
    check_ok "no timer run came back after uninstall, both state dirs are still gone" gone "$(path_of "$OWNER" state)" "$(path_of "$FOLLOWER" state)"
    expect_at_tag "$1" "uninstall left the checkout at v$1"
    check_eq "$(og status --porcelain)" "?? lib/e2e-untracked-marker" "and its work tree as it was"
}

BASE="$(head -n 1 /src/VERSION)" || exit 2
[[ $BASE =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || exit 2
V1="$(bump 1)" && V2="$(bump 2)" && V3="$(bump 3)" && V4="$(bump 4)" && V5="$(bump 5)" || exit 2
VIS_FINAL="$V4"
KEY="$(fake_key)" && [ -n "$KEY" ] || exit 2
GIT_VERSION="$(git --version)" && [ -n "$GIT_VERSION" ] || exit 2
mkdir -p "$LOGS" && : >"$WORK/runs.$OWNER" && : >"$WORK/runs.$FOLLOWER" || exit 2
