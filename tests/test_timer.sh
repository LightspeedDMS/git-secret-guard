# ^ external systemctl --user enable links timers.target.wants/<timer> to the unit file; the stand-in does not, the test creates the link
test_uninstall_removes_a_dangling_enable_link_that_points_at_our_unit_and_only_that() {
    local wants
    timer_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer"
    wants="$(unit_dir)/timers.target.wants"
    mkdir -p -- "$wants" && ln -s "$(unit_dir)/$TIMER" "$wants/$TIMER" && ln -s /nonexistent/other.timer "$wants/other.timer" || return 1
    rm -f -- "$(unit_dir)/$TIMER" || return 1
    gsg uninstall
    assert_rc 0 "uninstall with the timer file already gone"
    [ ! -L "$wants/$TIMER" ] || fail "the dangling link to our unit is still there"
    [ -L "$wants/other.timer" ] || fail "a dangling link that points elsewhere was removed"
    assert_no_file "$(unit_dir)/$SERVICE" "the service is removed as before"
    assert_contains "$OUT" "removed the dangling enable link $wants/$TIMER" "reported"
    timer_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer again"
    wants="$(unit_dir)/timers.target.wants"
    mkdir -p -- "$wants" && printf 'not a link\n' >"$wants/$TIMER" || return 1
    rm -f -- "$(unit_dir)/$TIMER" || return 1
    gsg uninstall
    assert_rc 0 "uninstall"
    assert_file "$wants/$TIMER" "a regular file at that path is never touched"
}

