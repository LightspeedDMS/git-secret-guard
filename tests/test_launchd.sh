test_install_with_timer_on_macos_writes_a_marked_plist_and_bootstraps_it() {
    local p text bash_bin
    launchd_begin || return 1
    gsg install --with-timer
    assert_rc 0 "install --with-timer on macOS"
    p="$(plist_path)"
    text="$(<"$p")"
    bash_bin="$(sed -n 's/^BASH_BIN=//p' "$LC_DATA/settings")"
    assert_eq "$(sed -n 1p "$p")" "$XML_LINE" "the plist starts with the xml declaration"
    assert_eq "$(sed -n 3p "$p")" "$MARKER_LINE" "and carries the marker on its third line, after the DOCTYPE"
    assert_contains "$text" $'<key>Label</key>\n    <string>'"$LABEL"$'</string>' "the label git-secret-guard owns"
    assert_contains "$text" $'<array>\n        <string>'"$bash_bin"$'</string>\n        <string>'"$LC_DATA"$'/bin/git-secret-guard</string>\n        <string>doctor</string>\n    </array>' "recorded bash, installed CLI, doctor"
    assert_contains "$text" $'<key>StartCalendarInterval</key>\n    <dict>\n        <key>Weekday</key>' "a weekly calendar interval"
    assert_contains "$text" $'<key>PATH</key>\n        <string>'"$(lc_first_git_dir)": "the PATH of the git install found first"
    assert_contains "$text" $'<key>StandardOutPath</key>\n    <string>'"$LC_STATE"$'/doctor.log</string>' "stdout goes to the log in the state dir"
    assert_contains "$text" $'<key>StandardErrorPath</key>\n    <string>'"$LC_STATE"$'/doctor.log</string>' "and stderr too"
    assert_contains "$(launchctl_log)" "bootstrap gui/$(id -u) $p" "the agent was loaded into the user's gui domain"
    assert_eq "$(state_value timer_installed)" yes "the state records the timer"
    assert_contains "$(<"$LC_DATA/settings")" "LAUNCHCTL_BIN=$SANDBOX/pathbin/launchctl" "the settings record the launchctl path found at install time"
    assert_not_contains "$(<"$LC_DATA/settings")" "SYSTEMCTL_BIN" "and no systemctl"
    assert_no_file "$LC_HOME/.config" "no systemd directory"
    assert_contains "$OUT" "weekly doctor agent loaded ($p); its output goes to $LC_STATE/doctor.log" "the summary says where the output goes"
}

