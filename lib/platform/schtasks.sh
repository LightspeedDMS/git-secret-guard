# shellcheck shell=bash disable=SC2153,SC2034
# ^ coupled CLI-only library, sourced after lib/platform/winupdate.sh; the Windows adapter of the updater (#132), one hourly Task Scheduler task of this user
# ^ invariant nothing here runs off Windows; install_timer, uninstall and autoupdate_report call it only when tools_is_windows holds
# ^ security schtasks comes from the settings file after install (SCHTASKS_BIN), never from PATH; MSYS_NO_PATHCONV=1 keeps /Create from being a path

# ^ external a task runs no shell; its action is a .cmd wrapper redirecting into the log, and /TR takes at most 261 characters
# ^ invariant line 2 of the wrapper is the marker; only a file with it is ours, as for the CLI wrapper (install_cli_cmd_is_ours)
GSG_SCHTASKS_MARKER='rem generated by git-secret-guard install --auto-update; uninstall removes this file'
GSG_SCHTASKS_TR_MAX=261

# ^ invariant sets REPLY = the absolute path of schtasks found on PATH; prints the refusal, naming --auto-update, when it is missing
schtasks_find() {
    install_find_bin schtasks && return 0
    printf '%s: schtasks is required for --auto-update but was not found on PATH (it ships with Windows, in System32); %s\n' "$GSG_NAME" "$(brew_unchanged_text)" >&2
    return 1
}

# ^ invariant sets REPLY = the Windows path of the action, the wrapper in quotes as /TR takes it
schtasks_action() {
    local win
    win="$(cygpath -w "$GSG_UPDATE_TASK_CMD")" || return 1
    REPLY="\"$win\""
}

# ^ invariant rc 1 = a value the wrapper would hold has a quote or a control character; cmd cannot take either inside set "NAME=value" or a quoted path
schtasks_check_values() {
    local what n
    local -a values=("$GSG_SHARE" "$GSG_STATE_DIR" "$HOME")
    timer_check_config_global || return 1
    for n in "${GSG_TIMER_ENV_NAMES[@]}"; do
        if [ -n "${!n:-}" ]; then values+=("${!n}"); fi
    done
    for what in "${values[@]}"; do
        case "$what" in
            *'"'* | *[[:cntrl:]]*)
                printf '%s: %s cannot be written into the update task wrapper (it holds a quote or a control character); %s\n' "$GSG_NAME" "${what//[[:cntrl:]]/?}" "$(brew_unchanged_text)" >&2
                return 1
                ;;
        esac
    done
}

# ^ invariant the wrapper text with CRLF line ends, $1 = the Windows path of bash.exe; % is doubled for cmd, the install's XDG and git variables are set again
# ^ why the variables, not the logon environment; an install run with XDG_DATA_HOME set must update the same share
schtasks_cmd_text() {
    local n share log home
    share="$(cygpath -m "$GSG_SHARE")" || return 1
    log="$(cygpath -w "$GSG_UPDATE_LOG")" || return 1
    home="$(cygpath -w "$HOME")" || return 1
    # ^ why the marker stays line 2 and setlocal is line 3, not the reverse; wrappers of earlier installs keep their marker where schtasks_cmd_is_ours reads it
    printf '%s\r\n' '@echo off' "$GSG_SCHTASKS_MARKER" 'setlocal DisableDelayedExpansion'
    # ^ why HOME too, not the logon profile's; the child install writes the CLI link under HOME, the wrong profile would get the link
    printf 'set "HOME=%s"\r\n' "${home//%/%%}"
    for n in "${GSG_TIMER_ENV_NAMES[@]}"; do
        if [ -n "${!n:-}" ]; then printf 'set "%s=%s"\r\n' "$n" "${!n//%/%%}"; fi
    done
    printf '"%s" "%s/bin/%s" update > "%s" 2>&1\r\n' "${1//%/%%}" "${share//%/%%}" "$GSG_NAME" "${log//%/%%}"
    printf 'exit /b %%errorlevel%%\r\n'
}

# ^ invariant sets REPLY = the Windows path of the bash install runs in, as install_cli_cmd_text names it
schtasks_bash() {
    local root
    root="$(cygpath -w /)" || return 1
    REPLY="${root%\\}\\bin\\bash.exe"
}

# ^ invariant true only for a regular file (never a link) whose second line is the marker => only an install wrote it
schtasks_cmd_is_ours() {
    local line=""
    if [ ! -f "$GSG_UPDATE_TASK_CMD" ] || [ -L "$GSG_UPDATE_TASK_CMD" ]; then return 1; fi
    { IFS= read -r line && IFS= read -r line; } <"$GSG_UPDATE_TASK_CMD" || return 1
    [ "${line%$'\r'}" = "$GSG_SCHTASKS_MARKER" ]
}

# ^ invariant $1 = schtasks; rc 0 = the task of our name runs our wrapper, 1 = it is somebody else's, 2 = there is none, 3 = Task Scheduler did not answer
# ^ external real schtasks exits 1 for a missing task and a failed query alike; the list of all tasks exits 0 once the service answers and names each task
# ^ why the file name of the action, not the whole path; schtasks prints it in the console code page and an accented user name would never match
schtasks_task_state() {
    local list out
    list="$(MSYS_NO_PATHCONV=1 "$1" /Query /FO CSV /NH 2>/dev/null </dev/null)" || return 3
    case $'\n'"$list" in
        *$'\n'"\"\\$GSG_UPDATE_TASK_NAME\","*) ;;
        *) return 2 ;;
    esac
    out="$(MSYS_NO_PATHCONV=1 "$1" /Query /TN "$GSG_UPDATE_TASK_NAME" /FO CSV /NH /V 2>/dev/null </dev/null)" || return 3
    case "$out" in
        *'\update-task.cmd'*) return 0 ;;
    esac
    return 1
}

# ^ order every check runs before any lasting change; $1 = schtasks; the first refusal ends it
schtasks_check_target() {
    local rc=0
    schtasks_check_values || return 1
    schtasks_action || return 1
    if [ "${#REPLY}" -gt "$GSG_SCHTASKS_TR_MAX" ]; then
        printf '%s: the task action %s is %s characters and Task Scheduler takes at most %s; shorten the state dir (XDG_STATE_HOME); %s\n' \
            "$GSG_NAME" "$REPLY" "${#REPLY}" "$GSG_SCHTASKS_TR_MAX" "$(brew_unchanged_text)" >&2
        return 1
    fi
    if { [ -e "$GSG_UPDATE_TASK_CMD" ] || [ -L "$GSG_UPDATE_TASK_CMD" ]; } && ! schtasks_cmd_is_ours; then
        printf '%s: %s exists and was not written by git-secret-guard; move it away and run install again; %s\n' "$GSG_NAME" "$GSG_UPDATE_TASK_CMD" "$(brew_unchanged_text)" >&2
        return 1
    fi
    schtasks_task_state "$1" || rc=$?
    if [ "$rc" -eq 3 ]; then
        printf '%s: could not ask Task Scheduler whether the task %s exists (%s /Query failed); run it by hand to see why; %s\n' "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" "$1" "$(brew_unchanged_text)" >&2
        return 1
    fi
    if [ "$rc" -eq 1 ]; then
        printf '%s: the task %s exists and was not created by git-secret-guard; delete it (schtasks /Delete /TN %s) and run install again; %s\n' \
            "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" "$GSG_UPDATE_TASK_NAME" "$(brew_unchanged_text)" >&2
        return 1
    fi
}

# ^ invariant the wrapper appears complete or not at all; the state dir is made first (the log lives there too)
schtasks_write_cmd() {
    local tmp
    schtasks_bash || return 1
    state_make_dir || return 1
    tmp="$(mktemp "$GSG_STATE_DIR/.gsg-task.XXXXXX")" || return 1
    if ! schtasks_cmd_text "$REPLY" >"$tmp" || ! mv -f -- "$tmp" "$GSG_UPDATE_TASK_CMD"; then
        rm -f -- "$tmp"
        return 1
    fi
}

# ^ order after the hook config and the state => a failing schtasks leaves the hook installed; the wrapper is written before the task names it
# ^ invariant $1 = schtasks; always /F, a task of ours is replaced and nothing asks a question; the schedule is the plain hour, no knob reaches it
schtasks_enable() {
    local rc
    if ! schtasks_write_cmd; then
        printf '%s: could not write %s; the hook is installed and scanning\n' "$GSG_NAME" "$GSG_UPDATE_TASK_CMD" >&2
        return 1
    fi
    schtasks_action || return 1
    MSYS_NO_PATHCONV=1 "$1" /Create /TN "$GSG_UPDATE_TASK_NAME" /SC HOURLY /TR "$REPLY" /F >/dev/null
    rc=$?
    if [ "$rc" -ne 0 ]; then
        printf '%s: could not register %s (schtasks exit %s); the hook is installed and scanning; fix the cause and run install --auto-update again\n' "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" "$rc" >&2
        return 1
    fi
    printf '%s: auto-update task registered (%s, every hour); its output goes to %s\n' "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" "$GSG_UPDATE_LOG"
    printf '%s: the task runs only while you are logged on\n' "$GSG_NAME"
}

# ^ invariant a plain install over a recorded auto-update rewrites the wrapper when it is ours and its text changed; the task and schtasks are left alone
schtasks_refresh() {
    local text
    if ! schtasks_cmd_is_ours; then return 0; fi
    schtasks_bash || return 1
    text="$(schtasks_cmd_text "$REPLY")" || return 1
    if [ "$(<"$GSG_UPDATE_TASK_CMD")" = "$text" ]; then return 0; fi
    schtasks_write_cmd || {
        printf '%s: could not rewrite %s; the hook is installed and scanning\n' "$GSG_NAME" "$GSG_UPDATE_TASK_CMD" >&2
        return 1
    }
}

# ^ order uninstall_timer before uninstall_share_dir => the settings naming schtasks still exist; a failure keeps wrapper, share dir and state for a rerun
# ^ security only a task running our wrapper is deleted and only a wrapper with the marker is removed; a foreign one is named and left
schtasks_uninstall() {
    local bin rc=0 mine=0 msg
    if [ "$ST_EXISTS" -ne 1 ] || [ "$ST_AUTO_UPDATE" != yes ]; then return 0; fi
    if schtasks_cmd_is_ours; then
        mine=1
    elif [ -e "$GSG_UPDATE_TASK_CMD" ] || [ -L "$GSG_UPDATE_TASK_CMD" ]; then
        printf '%s: %s was not written by git-secret-guard; left in place\n' "$GSG_NAME" "$GSG_UPDATE_TASK_CMD" >&2
    fi
    if ! load_settings "$GSG_SHARE/settings" || msg="$(tool_unusable schtasks "${SCHTASKS_BIN:-}")"; then
        if [ "$mine" -eq 0 ]; then return 0; fi
        printf '%s: %s; the wrapper, the share dir and the state are kept; delete the task yourself (schtasks /Delete /TN %s /F) and run uninstall again\n' \
            "$GSG_NAME" "${msg:-cannot read the settings}" "$GSG_UPDATE_TASK_NAME" >&2
        return 1
    fi
    bin="$SCHTASKS_BIN"
    schtasks_task_state "$bin" || rc=$?
    if [ "$rc" -eq 3 ]; then
        printf '%s: could not ask Task Scheduler whether the task %s exists (%s /Query failed); the wrapper, the share dir and the state are kept; fix the cause and run uninstall again\n' \
            "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" "$bin" >&2
        return 1
    fi
    if [ "$rc" -eq 1 ]; then
        printf '%s: the task %s was not created by git-secret-guard; left in place\n' "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" >&2
    elif [ "$rc" -eq 0 ]; then
        if ! MSYS_NO_PATHCONV=1 "$bin" /Delete /TN "$GSG_UPDATE_TASK_NAME" /F >/dev/null; then
            printf '%s: could not delete the task %s; the wrapper, the share dir and the state are kept; fix the cause and run uninstall again\n' "$GSG_NAME" "$GSG_UPDATE_TASK_NAME" >&2
            return 1
        fi
        uninstall_say "deleted the auto-update task $GSG_UPDATE_TASK_NAME"
    fi
    if [ "$mine" -eq 1 ]; then
        rm -f -- "$GSG_UPDATE_TASK_CMD" || return 1
        uninstall_say "removed the auto-update task wrapper $GSG_UPDATE_TASK_CMD"
    fi
}
