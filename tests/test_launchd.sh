test_a_failing_bootstrap_keeps_the_hook_and_a_rerun_loads_the_agent_over_a_loaded_one() {
    local uid
    launchd_begin || return 1
    uid="$(id -u)"
    printf 'bootstrap' >"$SANDBOX/launchctl.fail" || return 1
    gsg install --with-timer
    assert_rc 1 "launchctl cannot bootstrap the agent"
    assert_contains "$ERR" "could not load $LABEL (launchctl exit 1); the hook is installed and scanning; fix the cause and run install --with-timer again" "says what is true"
    assert_eq "$(gitx config --global --get hook.git-secret-guard.event)" pre-commit "the hook config is in place"
    assert_eq "$(state_value timer_installed)" yes "the state lets uninstall find the plist"
    assert_file "$(plist_path)" "the plist is written"
    rm -f -- "$SANDBOX/launchctl.fail" "$SANDBOX/launchctl.log" || return 1
    gsg install --with-timer
    assert_rc 0 "rerun once the cause is fixed"
    assert_contains "$(launchctl_log)" "bootstrap gui/$uid $(plist_path)" "loaded this time"
    : >"$SANDBOX/launchctl.log"
    gsg install --with-timer
    assert_rc 0 "install --with-timer over a loaded agent"
    assert_eq "$(launchctl_log)" "print gui/$uid/$LABEL"$'\n'"bootout gui/$uid/$LABEL"$'\n'"bootstrap gui/$uid $(plist_path)" "it is booted out first, a reload reads the new plist"
}

